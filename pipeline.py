КОРЕНЬ = Path(__file__).resolve().parent

# Ветки и деревья называются по номеру задачи. Имя ветки — единственное, что
# пайплайну разрешено толкать в репозиторий, и проверяется оно этим же
# образцом (см. _можно_пушить).
ВЕТКА = re.compile(r"^task-\d+$")

# Рабочие деревья кладём своим каталогом рядом с проектом. Не внутрь: внутри
# они попали бы и в git ls-files, и в поиск субагента, и каждый видел бы
# чужую работу. И не вперемешку с соседними проектами: три каталога и три
# журнала в общей папке — мусор у человека под руками.
#
# Латиница в именах не для красоты. Проверка javascript зовёт jsc, а тот
# читает argv как latin-1: из каталога с кириллицей в пути он не открывает
# файлы и сообщает об ошибке в каждом. Проверено на дне 35, см. check-js.py.
ДЕРЕВЬЯ = КОРЕНЬ.parent / f"{КОРЕНЬ.name}-worktrees"
ДЕРЕВО = "wt-task-{}"

# С какого порта искать свободный под серверы субагентов. Выше всех, что
# занимает run-local.sh, чтобы не столкнуться с работающим приложением.
ПОРТ_ОТ = 8810
ПОДЪЁМ_СЕКУНД = 30

# Сколько строк итога субагента показываем в отчёте.
ИТОГ_СТРОК = 12

# Сколько строк diff уходит модели на описание PR и сколько строк она пишет.
DIFF_МОДЕЛИ = 300
ОПИСАНИЕ_ТОКЕНОВ = 700


def токен() -> str:
    """Ключ GitHub для пуша и создания PR. Пусто — работаем как раньше.

    Один токен на обе работы, и это осознанно: иначе пуш шёл бы связкой
    ключей macOS, а PR — токеном, и права разъезжались бы по двум местам.
    Нужны ровно два: Contents: Read and write (пуш) и Pull requests: Read
    and write (сам PR), fine-grained, только на этот репозиторий.

    Пусто — не беда и не отказ: ветка уйдёт связкой, как и до сих пор, а
    вместо открытого PR будет ссылка на его создание.
    """
    ключ = (os.getenv("GITHUB_TOKEN") or "").strip()
    if ключ and not ключ.isascii():
        # Заголовки HTTP — latin-1, и ключ с лишним символом роняет запрос
        # UnicodeEncodeError'ом из глубины urllib, где про ключ не сказано ни
        # слова. Та же беда и то же лечение, что у ключа модели (llm.headers).
        raise Беда("В GITHUB_TOKEN есть символы вне ASCII — такой ключ не "
                   "отправить заголовком. Похоже, он скопирован с лишним "
                   "символом.")
    return ключ


def основная_ветка() -> str:
    """Ветка, от которой ветвимся и в которую метит PR.

    Спрашивается у git, а не зашивается: origin сам знает свою HEAD. Запасной
    master — на случай, когда ссылки на удалённую HEAD в репозитории нет
    (бывает после клона с --single-branch).
    """
    try:
        ссылка = _git_в_корне("symbolic-ref", "refs/remotes/origin/HEAD").strip()
    except Беда:
        return "master"
    return ссылка.rsplit("/", 1)[-1] or "master"


class Беда(RuntimeError):
    """Пайплайн остановился по причине, которую надо назвать человеку."""


# --- Репозиторий и задачи -------------------------------------------------


def репозиторий() -> tuple[str, str]:
    """Владелец и имя из origin. Отдельной переменной окружения не нужно."""
    # Через свой git, а не codebase.git: там белый список читающих подкоманд
    # для инструментов модели, и `remote` в нём нет. Расширять список ради
    # пайплайна неправильно — он не инструмент, и список охраняет не его.
    адрес = _git_в_корне("remote", "get-url", "origin").strip()
    совпало = re.search(r"[:/]([^/:]+)/([^/]+?)(?:\.git)?$", адрес)
    if not совпало:
        raise Беда(f"Не разобрать адрес origin: {адрес}")
    return совпало.group(1), совпало.group(2)


def _гитхаб(метод: str, путь: str, тело: dict | None = None, *, зачем: str):
    """Один разговор с GitHub. Разбор ошибок здесь, чтобы не расходился.

    Токен подставляется, если он есть. Чтение публичных issue в нём не
    нуждается — без токена это работает ровно так же, только с лимитом в
    60 запросов в час на адрес.

    Ни в одном сообщении об ошибке токена нет и быть не может: наружу идёт
    код ответа и объяснение, а не то, что мы послали.
    """
    хозяин, имя = репозиторий()
    заголовки = {"Accept": "application/vnd.github+json",
                 "User-Agent": f"{имя} day-35 pipeline",
                 "X-GitHub-Api-Version": "2022-11-28"}
    if ключ := токен():
        заголовки["Authorization"] = f"Bearer {ключ}"
    данные = json.dumps(тело).encode() if тело is not None else None
    запрос = urllib.request.Request(
        f"https://api.github.com/repos/{хозяин}/{имя}{путь}",
        data=данные, method=метод, headers=заголовки)
    try:
        with urllib.request.urlopen(запрос, timeout=30) as ответ:
            return json.load(ответ)
    except urllib.error.HTTPError as err:
        raise Беда(f"{зачем}: {_про_ответ(err)}") from err
    except (urllib.error.URLError, OSError, json.JSONDecodeError) as err:
        raise Беда(f"{зачем}: GitHub не ответил ({err})") from err


def _про_ответ(err: urllib.error.HTTPError) -> str:
    """Ответ GitHub словами. Пересказ, а не пересылка чужого текста целиком."""
    есть_ключ = bool(токен())
    если = {
        401: "ключ не принят — GITHUB_TOKEN просрочен или неверен",
        403: ("у ключа нет нужного права: для PR нужно Pull requests: Read "
              "and write, для пуша Contents: Read and write"
              if есть_ключ else
              "лимит запросов исчерпан (60 в час без ключа)"),
        404: ("репозитория или задачи нет, либо у ключа нет к ним доступа"
              if есть_ключ else "такой задачи нет или репозиторий закрыт"),
    }
    if err.code in если:
        return f"ответ {err.code} — {если[err.code]}"
    подробность = ""
    try:
        тело = json.loads(err.read().decode() or "{}")
        куски = [о.get("message", "") for о in (тело.get("errors") or [])]
        подробность = "; ".join([тело.get("message", ""), *куски]).strip("; ")
    except (ValueError, OSError):
        pass
    return f"ответ {err.code}" + (f" — {подробность[:200]}" if подробность else "")


def задача(номер: int) -> dict:
    """Одна issue из GitHub. Токен не обязателен: репозиторий открытый."""
    найдено = _гитхаб("GET", f"/issues/{номер}",
                      зачем=f"GitHub не отдал задачу #{номер}")
    if "pull_request" in найдено:
        raise Беда(f"#{номер} это pull request, а не задача.")
    return {"номер": найдено["number"],
            "название": найдено["title"] or "",
            "текст": (найдено.get("body") or "").strip()}


def поручение(issue: dict) -> str:
    """Текст задачи для субагента.

    Подставляет приложение, а не выпрашивает модель — тем же способом, каким
    день 33 кладёт тикет, а день 28 выдержки. Причина прежняя: данные, без
    которых работать нечем, кладёт тот, кто их знает.
    """
    тело = issue["текст"] or "(описания нет, делайте по названию)"
    return (f"Задача #{issue['номер']}: {issue['название']}\n\n{тело}\n\n"
            "Сделай её в этом рабочем дереве.")


# --- Рабочие деревья и серверы --------------------------------------------


def свободный_порт(от: int = ПОРТ_ОТ) -> int:
    """Первый незанятый порт начиная с указанного."""
    for порт in range(от, от + 50):
        with socket.socket() as гнездо:
            if гнездо.connect_ex(("127.0.0.1", порт)) != 0:
                return порт
    raise Беда(f"Свободного порта в диапазоне {от}…{от + 50} не нашлось.")


def завести_дерево(номер: int) -> tuple[Path, str]:
    """Своё рабочее дерево и ветка под задачу.

    Деревья, а не общая папка, и это не роскошь: в одной папке один HEAD и
    один индекс. Три агента не могут сидеть на трёх ветках, а `git commit`
    первого забрал бы недоделанную работу второго. Разделение по файлам от
    этого не спасает.
    """
    ветка = f"task-{номер}"
    ДЕРЕВЬЯ.mkdir(exist_ok=True)
    путь = ДЕРЕВЬЯ / ДЕРЕВО.format(номер)
    if путь.exists():
        raise Беда(f"{путь} уже есть — уберите: git worktree remove {путь}")
    если_местная = _git_в_корне("branch", "--list", ветка).strip()
    if если_местная:
        raise Беда(f"Ветка {ветка} уже есть здесь. Уберите её или возьмите "
                   f"другой номер: git branch -D {ветка}")
    # И на сервере тоже, до всякой работы. Замер дня 35: ветка от прошлого
    # прогона осталась в репозитории, субагент отработал полностью — и push
    # отказал «updates were rejected». Обидно вдвойне: труд потрачен, а
    # причина выясняется в самом конце. Спросить стоит одного запроса.
    если_там = _git_с_ключом(КОРЕНЬ, "ls-remote", "--heads", "origin", ветка)
    if если_там.returncode == 0 and если_там.stdout.strip():
        raise Беда(f"Ветка {ветка} уже есть на сервере — пуш всё равно "
                   f"откажет. Уберите её: git push origin --delete {ветка}")
    _git_в_корне("worktree", "add", str(путь), "-b", ветка, основная_ветка())
    return путь, ветка


def убрать_дерево(путь: Path) -> None:
    """Снимает дерево. Ветку не трогает: в ней работа, её судьбу решает человек."""
    try:
        _git_в_корне("worktree", "remove", "--force", str(путь))
    except Беда:
        pass


def _git_в_корне(*аргументы: str) -> str:
    """git в основном репозитории. Отдельно от codebase.git: тому разрешены
    только читающие подкоманды, а здесь нужны worktree, commit и push."""
    готово = subprocess.run(["git", *аргументы], cwd=КОРЕНЬ,
                            capture_output=True, text=True, timeout=120)
    if готово.returncode != 0:
        raise Беда(f"git {' '.join(аргументы)}: "
                   f"{(готово.stderr or готово.stdout).strip()[:300]}")
    return готово.stdout


def _git_в_дереве(путь: Path, *аргументы: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *аргументы], cwd=путь, capture_output=True,
                          text=True, timeout=300)


# Помощник, которым git спрашивает ключ. Токен он читает из окружения, а не
# получает аргументом, — и в этом весь смысл. В URL или в аргументах ключ
# увидел бы `ps` у любого на машине, и он осел бы в журналах шелла.
#
# Первый пустой credential.helper снимает osxkeychain: иначе связка ответила
# бы раньше нашего помощника, и токен бы не применился вовсе.
ПОМОЩНИК = ('!f(){ echo username=x-access-token; '
            'echo "password=$GITHUB_TOKEN"; };f')


def _git_с_ключом(путь: Path, *аргументы: str) -> subprocess.CompletedProcess:
    """git, который умеет ходить на сервер. С токеном — им, иначе связкой."""
    ключ = токен()
    если_ключ = ["-c", "credential.helper=", "-c", f"credential.helper={ПОМОЩНИК}"]
    return subprocess.run(
        ["git", *(если_ключ if ключ else []), *аргументы],
        cwd=путь, capture_output=True, text=True, timeout=300,
        env={**os.environ, "GITHUB_TOKEN": ключ} if ключ else None)


# Подъём серверов идёт по одному. Параллельно свободный порт выбирали бы
# одновременно — и выбрали бы один и тот же: между проверкой «занят ли» и
# тем мигом, когда uvicorn действительно займёт порт, проходят секунды.
# Замок держится до готовности сервера, поэтому гонки нет вовсе. Дорогая
# часть работы — сами субагенты — остаётся параллельной.
_ЗАМОК_ПОРТА = asyncio.Lock()


async def поднять_сервер(корень: Path) -> tuple[asyncio.subprocess.Process, str]:
    """Сервер проекта, смотрящий в это дерево и только в него.

    Корень приходит процессу переменной окружения, а не параметром вызова, —
    решение дня 31 остаётся в силе: модель не может попросить другой корень,
    потому что просить его негде.
    """
    журнал = корень.parent / f"{корень.name}.server.log"
    async with _ЗАМОК_ПОРТА:
        порт = свободный_порт()
        окружение = {**os.environ, "PROJECT_ROOT": str(корень)}
        with журнал.open("wb") as куда:
            процесс = await asyncio.create_subprocess_exec(
                str(КОРЕНЬ / ".venv" / "bin" / "uvicorn"), "project_mcp:app",
                "--host", "127.0.0.1", "--port", str(порт),
                "--log-level", "warning", cwd=КОРЕНЬ, env=окружение,
                stdout=куда, stderr=куда)
        адрес = f"http://127.0.0.1:{порт}/mcp"
        for _ in range(ПОДЪЁМ_СЕКУНД):
            if процесс.returncode is not None:
                raise Беда(f"Сервер проекта для {корень.name} упал при "
                           f"запуске:\n{_хвост_журнала(журнал)}")
            try:
                await mcp_tools.list_tools(адрес)
                return процесс, адрес
            except mcp_tools.MCPError:
                await asyncio.sleep(1)
        процесс.kill()
        raise Беда(f"Сервер проекта для {корень.name} не ответил за "
                   f"{ПОДЪЁМ_СЕКУНД} с:\n{_хвост_журнала(журнал)}")


def _хвост_журнала(журнал: Path, строк: int = 8) -> str:
    try:
        return "\n".join(журнал.read_text(errors="replace").splitlines()[-строк:])
    except OSError:
        return "(журнала нет)"


async def погасить(процесс: asyncio.subprocess.Process) -> None:
    """Гасит сервер. Уже мёртвый — не беда, а обычный случай при сбое.

    Без этой терпимости ProcessLookupError из уборки затирал настоящую
    причину сбоя: падало гашение, а почему упал сам прогон — не видно.
    """
    if процесс.returncode is not None:
        return
    try:
        процесс.terminate()
        await asyncio.wait_for(процесс.wait(), timeout=10)
    except ProcessLookupError:
        return
    except asyncio.TimeoutError:
        try:
            процесс.kill()
        except ProcessLookupError:
            return


async def свой_сервер(адрес: str, номер: int) -> list[dict]:
    """Один сервер списком — в том виде, в каком его ждёт _exchange.

    Строка базы здесь не заводится намеренно: включённый сервер виден всем
    ходам пользователя, а этот нужен ровно одному субагенту и ровно на время
    его работы. Схемы кладём сразу, поэтому за ними никто не пойдёт второй раз.
    """
    найдено = await mcp_tools.list_tools(адрес)
    return [{"id": -номер, "user_id": 0, "title": f"Задача #{номер}",
             "url": адрес, "enabled": 1, "error": None,
             "tools": mcp_tools.tools_json(найдено)}]


# --- Ворота и пуш ---------------------------------------------------------


def _можно_пушить(ветка: str) -> None:
    """Единственное, что пайплайну разрешено отправлять наружу.

    Проверка в коде, а не в промпте. Промпт — это просьба, а здесь нужен
    запрет: ветка вида task-<число>, новая, без force. master не трогается
    никогда, и это свойство кода, а не намерения.
    """
    if not ВЕТКА.match(ветка):
        raise Беда(f"Пайплайн пушит только ветки task-<номер>, а не «{ветка}».")


def запушить(путь: Path, ветка: str, issue: dict, ворота: str) -> str:
    """Собирает правку в коммит, отправляет ветку и возвращает тело для PR.

    Порядок тут не случаен. Описание строится по `git diff --cached`, то есть
    после `add` и до `commit`: после коммита индекс пуст, и рассказывать было
    бы не по чему. Один запрос к модели — два применения: тело коммита и тело
    PR. Повторять его дважды значило бы платить за то же самое.
    """
    _можно_пушить(ветка)
    if not _git_в_дереве(путь, "status", "--porcelain").stdout.strip():
        raise Беда("Менять нечего: субагент не оставил изменений.")
    собрано = _git_в_дереве(путь, "add", "-A")
    if собрано.returncode != 0:
        raise Беда(f"git add: {(собрано.stderr or собрано.stdout)[:200]}")

    тело = описание(путь, issue, ворота)
    коммит = _git_в_дереве(путь, "commit", "-m", _сообщение(issue, тело))
    if коммит.returncode != 0:
        raise Беда(f"git commit: {(коммит.stderr or коммит.stdout)[:200]}")

    отправить(путь, ветка)
    return тело


# Пуши идут по одному, хотя работа субагентов параллельна. Замер дня 35:
# три ветки ушли в один миг, две прошли, третья получила от GitHub
# «remote: fatal error in commit_refs» и отказ. Та же ветка, толкнутая
# отдельно, ушла с первого раза — значит дело не в коммите, а в том, что
# несколько обновлений ссылок пришли в репозиторий разом.
#
# Замок тут обычный, а не asyncio: запушить зовётся через to_thread, и
# асинхронный замок в чужом потоке не удержал бы ничего.
#
# Платим за это секундами на ветку из минуты работы. Теряли — всю задачу:
# в тот раз сто сорок шесть тысяч токенов и готовый код остались лежать в
# местной ветке, потому что последний шаг пришёлся не вовремя.
_ЗАМОК_ПУША = threading.Lock()
ПОВТОР_СЕКУНД = 3


def отправить(путь: Path, ветка: str) -> None:
    """Толкает ветку на сервер. По одной зараз и со второй попыткой.

    Повтор здесь не от суеверия: пуш — это сеть, и обрыв на ней не редкость,
    а цена неудачи несоразмерна — пропадает вся сделанная работа, хотя она
    уже прошла ворота. Повторный пуш той же ветки тем же коммитом безвреден:
    git сверяет ссылку, а не досылает что-то второй раз.
    """
    with _ЗАМОК_ПУША:
        for попытка in (1, 2):
            отправка = _git_с_ключом(путь, "push", "-u", "origin", ветка)
            if отправка.returncode == 0:
                return
            беда = (отправка.stderr or отправка.stdout).strip()
            if попытка == 1:
                time.sleep(ПОВТОР_СЕКУНД)
                continue
            raise Беда(f"git push (две попытки): {беда[:300]}")


def открыть_pr(ветка: str, заголовок: str, тело: str) -> tuple[str, str]:
    """Создаёт черновик PR. Возвращает адрес и чем дело кончилось.

    Черновиком намеренно: видно, что работа машинная и ждёт чтения, и
    случайно она не сольётся. Ревью дня 32 на черновиках запускается так же —
    оно стоит на `on: pull_request` без фильтров.

    Без ключа PR не создаётся вовсе, и это не поломка: возвращается ссылка на
    ручное создание, как было до появления токена.
    """
    хозяин, имя = репозиторий()
    if not токен():
        return (f"https://github.com/{хозяин}/{имя}/pull/new/{ветка}", "ссылка")
    if уже := _открытый_pr(ветка):
        return уже, "уже был"
    создан = _гитхаб("POST", "/pulls", {
        "title": заголовок,
        "head": ветка,
        "base": основная_ветка(),
        "body": тело,
        "draft": True,
    }, зачем=f"PR для {ветка} не создан")
    return создан.get("html_url", ""), "создан"


def _открытый_pr(ветка: str) -> str:
    """Адрес уже открытого PR на эту ветку, если он есть.

    Спрашивается до создания: повторный прогон не должен плодить вторые PR на
    ту же ветку. GitHub на это отвечает 422, но узнавать о своей ошибке из
    отказа — хуже, чем не делать её.
    """
    хозяин, _ = репозиторий()
    try:
        найдено = _гитхаб("GET", f"/pulls?head={хозяин}:{ветка}&state=open",
                          зачем="не спросить про открытые PR")
    except Беда:
        return ""
    return найдено[0].get("html_url", "") if найдено else ""


def описание(путь: Path, issue: dict, ворота: str) -> str:
    """Тело PR: факты собирает код, рассказ пишет модель.

    Отчёт субагента сюда не идёт, и это измерено, а не предположено. Из шести
    прогонов дня 35 четыре кончились внятной сводкой, а два — оборванной на
    полуслове отладочной болтовнёй: работа доделана и ворота пройдены, а
    рассказ обрезан пределом кругов. Описанием PR это было бы выдачей
    черновика мысли за отчёт.

    Поэтому порядок обратный привычному: сначала то, что нельзя переврать —
    diff, итог ворот, ссылка на задачу, — и лишь потом пересказ. Пересказа не
    вышло — PR всё равно читается.
    """
    номер = issue["номер"]
    статистика = _git_в_дереве(путь, "diff", "--cached", "--stat").stdout.strip()
    факты = (f"Задача: #{номер}\n\n"
             f"**Изменено**\n```\n{статистика or '(пусто)'}\n```\n\n"
             f"**Ворота**\n```\n{_кратко(ворота)}\n```\n\n"
             f"Закроет #{номер} при слиянии.\n\n"
             f"---\n*PR открыт автоматически: задача из очереди, код писал "
             f"субагент, проверки прогнал пайплайн. Черновик — прочитайте "
             f"прежде, чем снимать отметку.*")
    рассказ = _рассказ(путь, issue)
    return (f"{рассказ}\n\n{факты}" if рассказ else факты)


def _рассказ(путь: Path, issue: dict) -> str:
    """Короткое описание правки — одним запросом к модели, без инструментов.

    Тем же способом, каким делает ревью дня 32 (review.py). Не вышло — не
    беда: тело PR собрано из фактов и без этого.
    """
    import llm

    diff = _git_в_дереве(путь, "diff", "--cached").stdout
    if not diff.strip():
        return ""
    строки = diff.splitlines()
    если_длинно = ("\n… diff обрезан" if len(строки) > DIFF_МОДЕЛИ else "")
    сообщения = [
        {"role": "system", "content":
         "Опиши правку для описания pull request: два-четыре предложения о "
         "том, что изменено и зачем. Пиши по diff, ничего не додумывай. Без "
         "заголовков, списков и вступлений — только текст."},
        {"role": "user", "content":
         f"Задача #{issue['номер']}: {issue['название']}\n\n"
         f"{issue['текст'][:1500]}\n\nDiff:\n"
         + "\n".join(строки[:DIFF_МОДЕЛИ]) + если_длинно},
    ]
    try:
        готово = llm.complete(сообщения, thinking=False, temperature=0,
                              max_tokens=ОПИСАНИЕ_ТОКЕНОВ, keep_text=True)
    except Exception:  # noqa: BLE001 — описание не стоит того, чтобы ронять PR
        return ""
    return (готово.content or "").strip()


def _сообщение(issue: dict, тело: str) -> str:
    """Текст коммита: заголовок из задачи, а дальше тот же рассказ, что в PR.

    Заголовок берётся у issue и не выдумывается. Хвост `Closes #N` — чтобы
    задача закрылась слиянием, без отдельного действия.
    """
    номер = issue["номер"]
    первый = (тело.split("\n\n")[0] if тело else "").strip()
    шапка = f"Задача #{номер}: {issue['название']}".strip()[:72]
    куски = [шапка, первый, f"Closes #{номер}"]
    return "\n\n".join(к for к in куски if к)


def изменённое(путь: Path) -> list[str]:
    строки = _git_в_дереве(путь, "status", "--porcelain").stdout.splitlines()
    return [с[3:] for с in строки if с[3:]]


