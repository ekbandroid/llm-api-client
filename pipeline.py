async def субагент(user: dict, issue: dict, *, обмен) -> dict:
    """Одна задача целиком: дерево, сервер, работа, ворота, пуш.

    Возвращает итог, а не переписку: статус, файлы, ссылка, расход. Сам
    разговор остаётся отдельным диалогом — в него можно зайти и посмотреть,
    что субагент делал, но наверх он не поднимается.
    """
    номер = issue["номер"]
    итог = {"номер": номер, "название": issue["название"], "статус": "не начата",
            "файлы": [], "ссылка": "", "pr": "", "вызовов": 0, "токенов": 0,
            "диалог": 0, "беда": "", "ответ": ""}
    путь = процесс = None
    try:
        путь, ветка = завести_дерево(номер)
        процесс, адрес = await поднять_сервер(путь)
        серверы = await свой_сервер(адрес, номер)
        условия = commands.субагент(поручение(issue))
        диалог = db.create_conversation(
            user["id"], title=f"Задача #{номер} · субагент")
        итог["диалог"] = диалог["id"]
        outcome: dict = {}
        вызовов = 0
        async for кусок in обмен(диалог["id"], user, условия.question,
                                 outcome=outcome, command=условия,
                                 servers=серверы):
            вызовов += кусок.count('"type": "mcp"')
        итог["вызовов"] = вызовов
        итог["токенов"] = outcome.get("tokens") or 0
        итог["ответ"] = (outcome.get("answer") or "").strip()
        итог["файлы"] = изменённое(путь)
        if not итог["файлы"]:
            # Ветку убираем вместе с деревом: хранить в ней нечего, а пустые
            # task-* копились бы после каждого прогона. Когда правки есть,
            # ветка остаётся всегда — даже если ворота не пропустили: там
            # работа, и смотреть на неё человеку.
            итог["статус"] = "ничего не изменила"
            итог["пустая_ветка"] = ветка
            return итог
        # Ворота ещё раз, своими руками. Субагент их звал сам и по выводу
        # правился, но верить его пересказу нельзя: отчёт пишет модель, а
        # пускать в репозиторий должен код.
        прошло, вывод = await проверить(путь)
        if not прошло:
            итог["статус"] = "ворота не пройдены"
            итог["беда"] = вывод
            return итог
        тело = await asyncio.to_thread(запушить, путь, ветка, issue, вывод)
        итог["статус"] = "готова"
        # Ветка уже на сервере. Если PR не создастся — дальше не падаем: у
        # человека остаётся ссылка на ручное создание, а работа не потеряна.
        try:
            итог["ссылка"], итог["pr"] = await asyncio.to_thread(
                открыть_pr, ветка, f"#{номер} {issue['название']}".strip(), тело)
        except Беда as err:
            хозяин, имя = репозиторий()
            итог["ссылка"] = f"https://github.com/{хозяин}/{имя}/pull/new/{ветка}"
            итог["pr"] = "ссылка"
            итог["беда"] = str(err)
    except Беда as err:
        итог["статус"] = "сорвалась"
        итог["беда"] = str(err)
    except Exception as err:  # noqa: BLE001 — итог одного не должен ронять всех
        итог["статус"] = "сорвалась"
        итог["беда"] = f"{type(err).__name__}: {err}"
    finally:
        if процесс is not None:
            await погасить(процесс)
        if путь is not None:
            убрать_дерево(путь)
        if итог.get("пустая_ветка"):
            try:
                _git_в_корне("branch", "-D", итог["пустая_ветка"])
            except Беда:
                pass
    return итог


async def проверить(путь: Path) -> tuple[bool, str]:
    """Ворота перед пушем — отдельно от того раза, что звал субагент.

    Инструмент run_checks даёт субагенту чинить себя на ходу; этот вызов
    решает, пускать ли работу наружу. Роли разные, поэтому и зовутся дважды:
    отчёт субагента написала модель, а в репозиторий пускает код.
    """
    файлы = _git_в_дереве(путь, "ls-files").stdout.split()
    return await asyncio.to_thread(checks.прогнать, путь, файлы)


async def run(conversation_id: int, user: dict, условия, *, обмен
              ) -> AsyncIterator[str]:
    """Пайплайн как один ход чата: события идут по мере работы.

    Страница складывает `content` друг за другом, поэтому отчёт растёт на
    глазах, а не появляется через пять минут целиком. Ход занимает минуты —
    молчать всё это время нельзя.
    """
    import web  # лениво: web импортирует pipeline ради разбора команды

    части: list[str] = []

    def сказать(текст: str) -> str:
        части.append(текст)
        return web.sse({"type": "content", "text": текст})

    db.add_message(conversation_id, "user",
                   f"/issue {','.join(str(н) for н in условия.issues)}")
    начало = time.monotonic()
    порядок = "по одному" if условия.one_by_one else "одновременно"
    yield сказать(f"Задачи: {', '.join('#' + str(н) for н in условия.issues)} "
                  f"— {порядок}.\n\n")

    try:
        задачи = [задача(н) for н in условия.issues]
    except Беда as err:
        yield сказать(f"**Не вышло.** {err}\n")
        async for кусок in _закрыть(conversation_id, user, части, начало):
            yield кусок
        return

    for z in задачи:
        yield сказать(f"- #{z['номер']} {z['название']}\n")
    yield сказать("\nРаботают субагенты, у каждого своё рабочее дерево "
                  "и свой сервер проекта.\n\n")

    if условия.one_by_one:
        итоги = [await субагент(user, z, обмен=обмен) for z in задачи]
    else:
        итоги = list(await asyncio.gather(
            *(субагент(user, z, обмен=обмен) for z in задачи)))

    for и in итоги:
        yield сказать(_про_одну(и))
    yield сказать(_сводка(итоги, time.monotonic() - начало, условия.one_by_one))
    async for кусок in _закрыть(conversation_id, user, части, начало):
        yield кусок


def _про_одну(и: dict) -> str:
    значок = {"готова": "✓", "ворота не пройдены": "⨯",
              "сорвалась": "⨯", "ничего не изменила": "·"}.get(и["статус"], "·")
    строки = [f"### {значок} #{и['номер']} — {и['статус']}",
              f"*{и['название']}*", ""]
    if и["файлы"]:
        строки.append("Файлы: " + ", ".join(f"`{ф}`" for ф in и["файлы"]))
    if и["вызовов"]:
        строки.append(f"Вызовов инструментов: {и['вызовов']}, "
                      f"токенов {и['токенов']}.")
    if и["диалог"]:
        строки.append(f"Разговор субагента — диалог {и['диалог']}.")
    if и["ссылка"]:
        что = {"создан": "**PR открыт черновиком:**",
               "уже был": "**PR на эту ветку уже был:**",
               }.get(и["pr"], "**Ветка отправлена.** Открыть PR:")
        строки.append(f"\n{что} {и['ссылка']}")
        отмена = f"`git push origin --delete task-{и['номер']}`"
        строки.append("Отменить: " + (f"закрыть PR и {отмена}"
                                      if и["pr"] in ("создан", "уже был")
                                      else отмена))
    if и["беда"]:
        строки.append("\n```\n" + _кратко(и["беда"]) + "\n```")
    return "\n".join(строки) + "\n\n"


def _кратко(текст: str) -> str:
    строки = текст.splitlines()
    if len(строки) <= ИТОГ_СТРОК:
        return текст
    хвост = len(строки) - ИТОГ_СТРОК
    return "\n".join(строки[:ИТОГ_СТРОК]) + f"\n… ещё {хвост} строк"


def _сводка(итоги: list[dict], секунд: float, по_одному: bool) -> str:
    готовых = sum(1 for и in итоги if и["статус"] == "готова")
    токенов = sum(и["токенов"] for и in итоги)
    как = "последовательно" if по_одному else "параллельно"
    открыто = sum(1 for и in итоги if и["pr"] in ("создан", "уже был"))
    хвост = ""
    if открыто:
        хвост = (f"\n\nРевью дня 32 уже запущено: PR открыт, а оно стоит на "
                 f"`on: pull_request`. Разбор придёт комментарием.")
    elif готовых:
        хвост = ("\n\nРевью дня 32 запустится, как только PR будет открыт: "
                 "оно стоит на `on: pull_request`. Чтобы PR открывался сам, "
                 "задайте GITHUB_TOKEN — см. .env.example.")
    return (f"---\n\n**Итог:** готово {готовых} из {len(итоги)}, "
             f"{секунд:.0f} с {как}, токенов {токенов}.{хвост}\n")


async def _закрыть(conversation_id: int, user: dict, части: list[str],
                   начало: float) -> AsyncIterator[str]:
    """Сохраняет отчёт сообщением и закрывает ход — как это делает _canned."""
    import web

    ответ = "".join(части)
    saved = db.add_message(conversation_id, "assistant", ответ,
                           meta=json.dumps({"command": True, "pipeline": True},
                                           ensure_ascii=False))
    yield web.sse({"type": "done", "finish_reason": "stop", "usage": {},
                   "elapsed": round(time.monotonic() - начало, 2)})
    yield web.sse({"type": "saved", "message_id": saved["id"],
                   "title": web._owned(conversation_id, user)["title"]})
