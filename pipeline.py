"""День 35: issue → ветка → код → ворота → push → ссылка на PR.

Что здесь автоматизируется. В репозитории заводятся мелкие задачи на кодинг,
и каждую приходится одинаково проводить по одному и тому же пути: ветка,
правка, проверка, PR. Путь короткий, но повторяется, и в нём нечего решать —
значит, его и надо отдать.

Кто здесь агент, а кто нет — главное решение этого модуля.

Субагенты агенты: три независимые задачи, разные файлы, разные контексты.
Это Fan-Out, и параллельность тут настоящая, а не нарисованная.

Ворота — не агент. «Собралось» и «тест прошёл» это `returncode == 0`, а не
суждение. Модель, которую спрашивают «всё прошло?», может ответить «да»:
замер дня 34 дал ровно это — небольшая модель заключила, что в .env.example
нет строк «ключ=значение», не открыв файла. Ставить модель туда, где есть
точный предикат, значит самому внести в ворота ту ошибку, от которой ворота
и защищают.

Пуш — не агент. `git push` это команда. Модели здесь достаётся одна работа:
написать текст коммита, и это один запрос без инструментов.

Оркестратор — тоже не агент. Номера задач называет человек, выбирать нечего.
Агентом он станет в тот день, когда просьба будет звучать «разбери бэклог»:
вот тогда появится настоящая маршрутизация.

Проверяющий агент при этом есть, и писать его не пришлось: ревью дня 32
стоит на `on: pull_request`, то есть открытие PR запускает его само.
"""

import asyncio
import json
import os
import re
import socket
import subprocess
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import AsyncIterator

import checks
