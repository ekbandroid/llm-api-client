import db
import mcp_tools

КОРЕНЬ = Path(__file__).resolve().parent

# Ветки и деревья называются по номеру задачи. Имя ветки — единственное, что
# пайплайну разрешено толкать в репозиторий, и проверяется оно этим же
# образцом (см. _можно_пушить).
ВЕТКА = re.compile(r"^task-\d+$")

# Рабочие деревья кладём своим каталогом рядом с проектом. Не внутрь: внутри
# они попали бы и в git ls-files, и в поиск субагента, и каждый видел бы
# чужую работу. И не вперемешку с соседними проектами: три каталога и три
# журнала в общей папке — мусор у человека под руками.
#
# Латиница в именах не для красоты. Проверка javascript зовёт jsc, а тот
# читает argv как latin-1: из каталога с кириллицей в пути он не открывает
# файлы и сообщает об ошибке в каждом. Проверено на дне 35, см. check-js.py.
ДЕРЕВЬЯ = КОРЕНЬ.parent / f"{КОРЕНЬ.name}-worktrees"
ДЕРЕВО = "wt-task-{}"

# С какого порта искать свободный под серверы субагентов. Выше всех, что
# занимает run-local.sh, чтобы не столкнуться с работающим приложением.
ПОРТ_ОТ = 8810
ПОДЪЁМ_СЕКУНД = 30

# Сколько строк итога субагента показываем в отчёте.
ИТОГ_СТРОК = 12


class Беда(RuntimeError):
    """Пайплайн остановился по причине, которую надо назвать человеку."""


# --- Репозиторий и задачи -------------------------------------------------


def репозиторий() -> tuple[str, str]:
    """Владелец и имя из origin. Отдельной переменной окружения не нужно."""
    # Через свой git, а не codebase.git: там белый список читающих подкоманд
    # для инструментов модели, и `remote` в нём нет. Расширять список ради
    # пайплайна неправильно — он не инструмент, и список охраняет не его.
    адрес = _git_в_корне("remote", "get-url", "origin").strip()
    совпало = re.search(r"[:/]([^/:]+)/([^/]+?)(?:\.git)?$", адрес)
    if not совпало:
        raise Беда(f"Не разобрать адрес origin: {адрес}")
    return совпало.group(1), совпало.group(2)


def задача(номер: int) -> dict:
    """Одна issue из GitHub. Без токена: репозиторий открытый.

    Токена здесь нет намеренно. Чтение публичных issue в нём не нуждается, а
    всё, для чего он понадобился бы — создать PR, — оставлено человеку одним
    кликом. Доступ, который не нужен, лучше не просить.
    """
    хозяин, имя = репозиторий()
    адрес = f"https://api.github.com/repos/{хозяин}/{имя}/issues/{номер}"
    запрос = urllib.request.Request(адрес, headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": f"{имя} day-35 pipeline",
    })
    try:
        with urllib.request.urlopen(запрос, timeout=20) as ответ:
            найдено = json.load(ответ)
    except urllib.error.HTTPError as err:
        если = {403: "лимит запросов исчерпан (60 в час без токена)",
                404: "такой задачи нет или репозиторий закрыт"}
        raise Беда(f"GitHub не отдал задачу #{номер}: "
                   f"{если.get(err.code, f'ответ {err.code}')}") from err
    except (urllib.error.URLError, OSError, json.JSONDecodeError) as err:
        raise Беда(f"GitHub не ответил про задачу #{номер}: {err}") from err
    if "pull_request" in найдено:
        raise Беда(f"#{номер} это pull request, а не задача.")
    return {"номер": найдено["number"],
            "название": найдено["title"] or "",
            "текст": (найдено.get("body") or "").strip()}


def поручение(issue: dict) -> str:
    """Текст задачи для субагента.

    Подставляет приложение, а не выпрашивает модель — тем же способом, каким
    день 33 кладёт тикет, а день 28 выдержки. Причина прежняя: данные, без
    которых работать нечем, кладёт тот, кто их знает.
    """
    тело = issue["текст"] or "(описания нет, делайте по названию)"
    return (f"Задача #{issue['номер']}: {issue['название']}\n\n{тело}\n\n"
            "Сделай её в этом рабочем дереве.")


# --- Рабочие деревья и серверы --------------------------------------------


def свободный_порт(от: int = ПОРТ_ОТ) -> int:
    """Первый незанятый порт начиная с указанного."""
    for порт in range(от, от + 50):
        with socket.socket() as гнездо:
            if гнездо.connect_ex(("127.0.0.1", порт)) != 0:
                return порт
    raise Беда(f"Свободного порта в диапазоне {от}…{от + 50} не нашлось.")


def завести_дерево(номер: int) -> tuple[Path, str]:
    """Своё рабочее дерево и ветка под задачу.

    Деревья, а не общая папка, и это не роскошь: в одной папке один HEAD и
    один индекс. Три агента не могут сидеть на трёх ветках, а `git commit`
    первого забрал бы недоделанную работу второго. Разделение по файлам от
    этого не спасает.
    """
    ветка = f"task-{номер}"
    ДЕРЕВЬЯ.mkdir(exist_ok=True)
    путь = ДЕРЕВЬЯ / ДЕРЕВО.format(номер)
    if путь.exists():
        raise Беда(f"{путь} уже есть — уберите: git worktree remove {путь}")
    есть = _git_в_корне("branch", "--list", ветка).strip()
    if есть:
        raise Беда(f"Ветка {ветка} уже есть. Уберите её или возьмите другой "
                   f"номер: git branch -D {ветка}")
    _git_в_корне("worktree", "add", str(путь), "-b", ветка, "master")
    return путь, ветка


def убрать_дерево(путь: Path) -> None:
    """Снимает дерево. Ветку не трогает: в ней работа, её судьбу решает человек."""
    try:
        _git_в_корне("worktree", "remove", "--force", str(путь))
    except Беда:
        pass


def _git_в_корне(*аргументы: str) -> str:
    """git в основном репозитории. Отдельно от codebase.git: тому разрешены
    только читающие подкоманды, а здесь нужны worktree, commit и push."""
    готово = subprocess.run(["git", *аргументы], cwd=КОРЕНЬ,
                            capture_output=True, text=True, timeout=120)
    if готово.returncode != 0:
        raise Беда(f"git {' '.join(аргументы)}: "
                   f"{(готово.stderr or готово.stdout).strip()[:300]}")
    return готово.stdout


def _git_в_дереве(путь: Path, *аргументы: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *аргументы], cwd=путь, capture_output=True,
                          text=True, timeout=300)


# Подъём серверов идёт по одному. Параллельно свободный порт выбирали бы
# одновременно — и выбрали бы один и тот же: между проверкой «занят ли» и
# тем мигом, когда uvicorn действительно займёт порт, проходят секунды.
# Замок держится до готовности сервера, поэтому гонки нет вовсе. Дорогая
# часть работы — сами субагенты — остаётся параллельной.
_ЗАМОК_ПОРТА = asyncio.Lock()


async def поднять_сервер(корень: Path) -> tuple[asyncio.subprocess.Process, str]:
    """Сервер проекта, смотрящий в это дерево и только в него.

    Корень приходит процессу переменной окружения, а не параметром вызова, —
    решение дня 31 остаётся в силе: модель не может попросить другой корень,
    потому что просить его негде.
    """
    журнал = корень.parent / f"{корень.name}.server.log"
    async with _ЗАМОК_ПОРТА:
        порт = свободный_порт()
        окружение = {**os.environ, "PROJECT_ROOT": str(корень)}
        with журнал.open("wb") as куда:
            процесс = await asyncio.create_subprocess_exec(
                str(КОРЕНЬ / ".venv" / "bin" / "uvicorn"), "project_mcp:app",
                "--host", "127.0.0.1", "--port", str(порт),
                "--log-level", "warning", cwd=КОРЕНЬ, env=окружение,
                stdout=куда, stderr=куда)
        адрес = f"http://127.0.0.1:{порт}/mcp"
        for _ in range(ПОДЪЁМ_СЕКУНД):
            if процесс.returncode is not None:
                raise Беда(f"Сервер проекта для {корень.name} упал при "
                           f"запуске:\n{_хвост_журнала(журнал)}")
            try:
                await mcp_tools.list_tools(адрес)
                return процесс, адрес
            except mcp_tools.MCPError:
                await asyncio.sleep(1)
        процесс.kill()
        raise Беда(f"Сервер проекта для {корень.name} не ответил за "
                   f"{ПОДЪЁМ_СЕКУНД} с:\n{_хвост_журнала(журнал)}")


def _хвост_журнала(журнал: Path, строк: int = 8) -> str:
    try:
        return "\n".join(журнал.read_text(errors="replace").splitlines()[-строк:])
    except OSError:
        return "(журнала нет)"


async def погасить(процесс: asyncio.subprocess.Process) -> None:
    """Гасит сервер. Уже мёртвый — не беда, а обычный случай при сбое.

    Без этой терпимости ProcessLookupError из уборки затирал настоящую
    причину сбоя: падало гашение, а почему упал сам прогон — не видно.
    """
    if процесс.returncode is not None:
        return
    try:
        процесс.terminate()
        await asyncio.wait_for(процесс.wait(), timeout=10)
    except ProcessLookupError:
        return
    except asyncio.TimeoutError:
        try:
            процесс.kill()
        except ProcessLookupError:
            return


async def свой_сервер(адрес: str, номер: int) -> list[dict]:
    """Один сервер списком — в том виде, в каком его ждёт _exchange.

    Строка базы здесь не заводится намеренно: включённый сервер виден всем
    ходам пользователя, а этот нужен ровно одному субагенту и ровно на время
    его работы. Схемы кладём сразу, поэтому за ними никто не пойдёт второй раз.
    """
    найдено = await mcp_tools.list_tools(адрес)
    return [{"id": -номер, "user_id": 0, "title": f"Задача #{номер}",
             "url": адрес, "enabled": 1, "error": None,
             "tools": mcp_tools.tools_json(найдено)}]


# --- Ворота и пуш ---------------------------------------------------------


def _можно_пушить(ветка: str) -> None:
    """Единственное, что пайплайну разрешено отправлять наружу.

    Проверка в коде, а не в промпте. Промпт — это просьба, а здесь нужен
    запрет: ветка вида task-<число>, новая, без force. master не трогается
    никогда, и это свойство кода, а не намерения.
    """
    if not ВЕТКА.match(ветка):
        raise Беда(f"Пайплайн пушит только ветки task-<номер>, а не «{ветка}».")


def запушить(путь: Path, ветка: str) -> str:
    """Коммит и пуш ветки. Возвращает ссылку на создание PR."""
    _можно_пушить(ветка)
    готово = _git_в_дереве(путь, "status", "--porcelain")
    if not готово.stdout.strip():
        raise Беда("Менять нечего: субагент не оставил изменений.")
    for шаг in (("add", "-A"), ("commit", "-m", _сообщение(путь, ветка))):
        итог = _git_в_дереве(путь, *шаг)
        if итог.returncode != 0:
            raise Беда(f"git {шаг[0]}: {(итог.stderr or итог.stdout)[:200]}")
    отправка = _git_в_дереве(путь, "push", "-u", "origin", ветка)
    if отправка.returncode != 0:
        raise Беда(f"git push: {(отправка.stderr or отправка.stdout)[:300]}")
    ссылка = re.search(r"https://\S*/pull/new/\S+", отправка.stderr or "")
    if ссылка:
        return ссылка.group(0)
    хозяин, имя = репозиторий()
    return f"https://github.com/{хозяин}/{имя}/pull/new/{ветка}"


def _сообщение(путь: Path, ветка: str) -> str:
    """Текст коммита. Пока без модели: список файлов честнее выдумки."""
    номер = ветка.split("-")[-1]
    файлы = _git_в_дереве(путь, "status", "--porcelain").stdout.split()
    имена = [ф for ф in файлы if "/" in ф or "." in ф][:5]
    хвост = "\n".join(f"  {и}" for и in имена)
    return f"Задача #{номер}\n\nИзменено:\n{хвост}\n\nCloses #{номер}"


def изменённое(путь: Path) -> list[str]:
    строки = _git_в_дереве(путь, "status", "--porcelain").stdout.splitlines()
    return [с[3:] for с in строки if с[3:]]


# --- Оркестрация ----------------------------------------------------------


async def субагент(user: dict, issue: dict, *, обмен) -> dict:
    """Одна задача целиком: дерево, сервер, работа, ворота, пуш.

    Возвращает итог, а не переписку: статус, файлы, ссылка, расход. Сам
    разговор остаётся отдельным диалогом — в него можно зайти и посмотреть,
    что субагент делал, но наверх он не поднимается.
    """
    номер = issue["номер"]
    итог = {"номер": номер, "название": issue["название"], "статус": "не начата",
            "файлы": [], "ссылка": "", "вызовов": 0, "токенов": 0,
            "диалог": 0, "беда": "", "ответ": ""}
    путь = процесс = None
    try:
        путь, ветка = завести_дерево(номер)
        процесс, адрес = await поднять_сервер(путь)
        серверы = await свой_сервер(адрес, номер)
        условия = commands.субагент(поручение(issue))
        диалог = db.create_conversation(
            user["id"], title=f"Задача #{номер} · субагент")
        итог["диалог"] = диалог["id"]
        outcome: dict = {}
        вызовов = 0
        async for кусок in обмен(диалог["id"], user, условия.question,
                                 outcome=outcome, command=условия,
                                 servers=серверы):
            вызовов += кусок.count('"type": "mcp"')
        итог["вызовов"] = вызовов
        итог["токенов"] = outcome.get("tokens") or 0
        итог["ответ"] = (outcome.get("answer") or "").strip()
        итог["файлы"] = изменённое(путь)
        if not итог["файлы"]:
            # Ветку убираем вместе с деревом: хранить в ней нечего, а пустые
            # task-* копились бы после каждого прогона. Когда правки есть,
            # ветка остаётся всегда — даже если ворота не пропустили: там
            # работа, и смотреть на неё человеку.
            итог["статус"] = "ничего не изменила"
            итог["пустая_ветка"] = ветка
            return итог
        # Ворота ещё раз, своими руками. Субагент их звал сам и по выводу
        # правился, но верить его пересказу нельзя: отчёт пишет модель, а
        # пускать в репозиторий должен код.
        прошло, вывод = await проверить(путь)
        if not прошло:
            итог["статус"] = "ворота не пройдены"
            итог["беда"] = вывод
            return итог
        итог["ссылка"] = запушить(путь, ветка)
        итог["статус"] = "готова"
    except Беда as err:
        итог["статус"] = "сорвалась"
        итог["беда"] = str(err)
    except Exception as err:  # noqa: BLE001 — итог одного не должен ронять всех
        итог["статус"] = "сорвалась"
        итог["беда"] = f"{type(err).__name__}: {err}"
    finally:
        if процесс is not None:
            await погасить(процесс)
        if путь is not None:
            убрать_дерево(путь)
        if итог.get("пустая_ветка"):
            try:
                _git_в_корне("branch", "-D", итог["пустая_ветка"])
            except Беда:
                pass
    return итог


async def проверить(путь: Path) -> tuple[bool, str]:
    """Ворота перед пушем — отдельно от того раза, что звал субагент.

    Инструмент run_checks даёт субагенту чинить себя на ходу; этот вызов
    решает, пускать ли работу наружу. Роли разные, поэтому и зовутся дважды:
    отчёт субагента написала модель, а в репозиторий пускает код.
    """
    файлы = _git_в_дереве(путь, "ls-files").stdout.split()
    return await asyncio.to_thread(checks.прогнать, путь, файлы)


async def run(conversation_id: int, user: dict, условия, *, обмен
              ) -> AsyncIterator[str]:
    """Пайплайн как один ход чата: события идут по мере работы.

    Страница складывает `content` друг за другом, поэтому отчёт растёт на
    глазах, а не появляется через пять минут целиком. Ход занимает минуты —
    молчать всё это время нельзя.
    """
    import web  # лениво: web импортирует pipeline ради разбора команды

    части: list[str] = []

    def сказать(текст: str) -> str:
        части.append(текст)
        return web.sse({"type": "content", "text": текст})

    db.add_message(conversation_id, "user",
                   f"/issue {','.join(str(н) for н in условия.issues)}")
    начало = time.monotonic()
    порядок = "по одному" if условия.one_by_one else "одновременно"
    yield сказать(f"Задачи: {', '.join('#' + str(н) for н in условия.issues)} "
                  f"— {порядок}.\n\n")

    try:
        задачи = [задача(н) for н in условия.issues]
    except Беда as err:
        yield сказать(f"**Не вышло.** {err}\n")
        async for кусок in _закрыть(conversation_id, user, части, начало):
            yield кусок
        return

    for z in задачи:
        yield сказать(f"- #{z['номер']} {z['название']}\n")
    yield сказать("\nРаботают субагенты, у каждого своё рабочее дерево "
                  "и свой сервер проекта.\n\n")

    if условия.one_by_one:
        итоги = [await субагент(user, z, обмен=обмен) for z in задачи]
    else:
        итоги = list(await asyncio.gather(
            *(субагент(user, z, обмен=обмен) for z in задачи)))

    for и in итоги:
        yield сказать(_про_одну(и))
    yield сказать(_сводка(итоги, time.monotonic() - начало, условия.one_by_one))
    async for кусок in _закрыть(conversation_id, user, части, начало):
        yield кусок


def _про_одну(и: dict) -> str:
    значок = {"готова": "✓", "ворота не пройдены": "⨯",
              "сорвалась": "⨯", "ничего не изменила": "·"}.get(и["статус"], "·")
    строки = [f"### {значок} #{и['номер']} — {и['статус']}",
              f"*{и['название']}*", ""]
    if и["файлы"]:
        строки.append("Файлы: " + ", ".join(f"`{ф}`" for ф in и["файлы"]))
    if и["вызовов"]:
        строки.append(f"Вызовов инструментов: {и['вызовов']}, "
                      f"токенов {и['токенов']}.")
    if и["диалог"]:
        строки.append(f"Разговор субагента — диалог {и['диалог']}.")
    if и["ссылка"]:
        строки.append(f"\n**Ветка отправлена.** Открыть PR: {и['ссылка']}\n"
                      f"Отменить: `git push origin --delete task-{и['номер']}`")
    if и["беда"]:
        строки.append("\n```\n" + _кратко(и["беда"]) + "\n```")
    return "\n".join(строки) + "\n\n"


def _кратко(текст: str) -> str:
    строки = текст.splitlines()
    if len(строки) <= ИТОГ_СТРОК:
        return текст
    хвост = len(строки) - ИТОГ_СТРОК
    return "\n".join(строки[:ИТОГ_СТРОК]) + f"\n… ещё {хвост} строк"


def _сводка(итоги: list[dict], секунд: float, по_одному: bool) -> str:
    готовых = sum(1 for и in итоги if и["статус"] == "готова")
    токенов = sum(и["токенов"] for и in итоги)
    как = "последовательно" if по_одному else "параллельно"
    хвост = ""
    if готовых:
        хвост = ("\n\nРевью дня 32 запустится само, как только PR будет "
                 "открыт: оно стоит на `on: pull_request`.")
    return (f"---\n\n**Итог:** готово {готовых} из {len(итоги)}, "
             f"{секунд:.0f} с {как}, токенов {токенов}.{хвост}\n")


async def _закрыть(conversation_id: int, user: dict, части: list[str],
                   начало: float) -> AsyncIterator[str]:
    """Сохраняет отчёт сообщением и закрывает ход — как это делает _canned."""
    import web

    ответ = "".join(части)
    saved = db.add_message(conversation_id, "assistant", ответ,
                           meta=json.dumps({"command": True, "pipeline": True},
                                           ensure_ascii=False))
    yield web.sse({"type": "done", "finish_reason": "stop", "usage": {},
                   "elapsed": round(time.monotonic() - начало, 2)})
    yield web.sse({"type": "saved", "message_id": saved["id"],
                   "title": web._owned(conversation_id, user)["title"]})
