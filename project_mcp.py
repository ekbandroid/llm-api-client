"""Сервер MCP про сам репозиторий: ветка, изменённое, diff, коммиты.

Первый наш инструмент, запускающий внешнюю программу, поэтому про границы
стоит сказать прямо. Корень фиксирован переменной `PROJECT_ROOT`, а не
приходит от модели: иначе инструмент читал бы любой репозиторий на машине.
Подкоманды git — из списка в codebase.ALLOWED, то есть `push` в нём нет даже
теоретически. Аргументы передаются списком, без shell.

День 34 добавил сюда чтение и запись файлов, и граница описана там одной
фразой: работаем с тем, что видит git, и никогда с тем, что git велено
игнорировать. День 35 добавил `run_checks` — он запускает проверки проекта и
единственный здесь ничего не принимает от модели: ни пути, ни команды. Модель
решает, *когда* проверить, но не *что* запустить.

Сервер локальный по устройству. На сервере приложения истории нет вовсе — код
кладётся `git archive`'ом, без .git, — и там все четыре инструмента честно
скажут, что репозитория не видят. Поэтому юнита для него нет: служба, которая
ничего не может ответить, памяти стоит столько же, сколько рабочая.

    uvicorn project_mcp:app --host 127.0.0.1 --port 8004
"""

import asyncio
from pathlib import Path
from typing import Annotated

from mcp.server.mcpserver import MCPServer
from pydantic import Field

import checks
import codebase

# Сколько строк diff отдаём. Предел не из осторожности, а из арифметики: diff
# на тысячу строк — это около десяти тысяч токенов, то есть окно контекста
# местной модели целиком, и минута разбора на процессоре (замер дня 29 —
# 13 с на тысячу токенов).
DIFF_LINES = 400

# Сколько коммитов максимум, сколько бы ни попросили.
COMMITS_MAX = 50

server = MCPServer(
    name="Проект: git и состояние репозитория",
    version="1.0.0",
    instructions=(
        "Состояние репозитория, над которым идёт работа: текущая ветка, "
        "изменённые файлы, diff рабочего каталога, последние коммиты. "
        "Содержимое файлов этими инструментами не читается — для него есть "
        "поиск по подключённым наборам документов проекта. Если репозитория "
        "нет, инструменты скажут об этом словами."
    ),
)


def _обрезать(текст: str, предел: int) -> str:
    """Отдаёт не больше предела строк и говорит, сколько осталось за краем."""
    строки = текст.splitlines()
    if len(строки) <= предел:
        return текст.rstrip()
    хвост = len(строки) - предел
    return "\n".join(строки[:предел]) + f"\n… ещё {хвост} строк, здесь не показаны"


def _нет_репозитория() -> str:
    return (f"В {codebase.ROOT} нет git-репозитория, поэтому про ветку, "
            f"изменения и коммиты сказать нечего. Так и бывает на сервере: "
            f"код там кладётся git archive'ом, без истории.")


@server.tool()
async def git_branch() -> str:
    """Текущая ветка репозитория и насколько она расходится с origin.

    Отвечает на вопрос «где я сейчас»: имя ветки, последний коммит и сколько
    коммитов она опережает или отстаёт от своей удалённой пары.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    try:
        ветка = codebase.git("rev-parse", "--abbrev-ref", "HEAD").strip()
        последний = codebase.git("log", "-1", "--format=%h %s").strip()
    except codebase.GitError as err:
        return f"git не ответил: {err}"

    расхождение = ""
    try:
        # Пары может не быть вовсе — у новой ветки её нет, и это не ошибка.
        счёт = codebase.git("rev-list", "--left-right", "--count",
                            f"{ветка}...origin/{ветка}")
    except codebase.GitError:
        расхождение = ", удалённой пары нет"
    else:
        впереди, позади = (счёт.split() + ["0", "0"])[:2]
        if впереди != "0" or позади != "0":
            расхождение = f", впереди origin на {впереди}, позади на {позади}"
        else:
            расхождение = ", совпадает с origin"
    return f"Ветка {ветка}{расхождение}. Последний коммит: {последний}"


@server.tool()
async def changed_files() -> str:
    """Какие файлы изменены в рабочем каталоге и что уже добавлено в индекс.

    Нужно, чтобы говорить о текущей работе, а не о последнем коммите: правка,
    которую ещё не закоммитили, в истории не видна.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    try:
        отметки = codebase.git("status", "--porcelain").splitlines()
    except codebase.GitError as err:
        return f"git не ответил: {err}"
    if not отметки:
        return "Рабочий каталог чист: незакоммиченных правок нет."

    # Первые две буквы строки status: слева индекс, справа рабочий каталог.
    словами = {"M": "изменён", "A": "добавлен", "D": "удалён", "R": "переименован",
               "C": "скопирован", "?": "не отслеживается", "!": "игнорируется"}
    строки = []
    for отметка in отметки:
        код, путь = отметка[:2], отметка[3:]
        if код in ("??", "!!"):
            # Обе буквы одинаковые, и «в индексе не отслеживается, в каталоге
            # не отслеживается» — это одно и то же сказанное дважды.
            строки.append(f"  {путь} — {словами[код[0]]}")
            continue
        где = []
        if код[0].strip():
            где.append(f"в индексе {словами.get(код[0], код[0])}")
        if код[1].strip():
            где.append(f"в каталоге {словами.get(код[1], код[1])}")
        строки.append(f"  {путь} — {', '.join(где) or код}")
    return f"Изменённых файлов {len(отметки)}:\n" + _обрезать("\n".join(строки), 60)


@server.tool()
async def git_diff(
    path: Annotated[str, Field(
        description="Файл или папка внутри проекта, чтобы сузить diff. "
                    "Пусто — весь рабочий каталог.")] = "",
    staged: Annotated[bool, Field(
        description="True — показать добавленное в индекс (git diff --staged) "
                    "вместо незакоммиченного в рабочем каталоге.")] = False,
) -> str:
    """Diff рабочего каталога: что именно изменилось в коде.

    Вывод обрезается — очень большой diff в запрос не влезет, и об обрезке
    будет сказано в самом ответе.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    аргументы = ["diff"]
    if staged:
        аргументы.append("--staged")
    try:
        if path:
            # Путь от модели проверяем: внутрь корня и не дальше.
            цель = codebase.inside(path)
            аргументы += ["--", str(цель.relative_to(codebase.ROOT))]
        текст = codebase.git(*аргументы)
    except codebase.GitError as err:
        return f"Не вышло: {err}"
    if not текст.strip():
        где = "в индексе" if staged else "в рабочем каталоге"
        return f"Пусто: {где}" + (f" по пути {path}" if path else "") + " изменений нет."
    return _обрезать(текст, DIFF_LINES)


@server.tool()
async def recent_commits(
    limit: Annotated[int, Field(
        description="Сколько последних коммитов показать, 1–50.")] = 10,
) -> str:
    """Последние коммиты: что в проекте делали в последнее время.

    По одной строке на коммит — хеш, дата, автор и заголовок.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    сколько = max(1, min(int(limit or 10), COMMITS_MAX))
    try:
        текст = codebase.git(
            "log", f"-{сколько}", "--date=short", "--format=%h %ad %an: %s")
    except codebase.GitError as err:
        return f"git не ответил: {err}"
    return текст.rstrip() or "В репозитории нет коммитов."


# ---------- файлы проекта ----------
#
# В дне 31 инструмента «прочитай файл» здесь намеренно не было, и причина была
# записана так: «содержимое доступно через поиск по индексу, а такой инструмент
# означал бы чтение чего угодно на машине по просьбе модели». Для
# ассистента-справочника это верно. Для работы с файлами — нет: индекс это
# снимок, нарезанный кусками, а чтобы править файл, нужно его точное нынешнее
# содержимое. Отказ снят, граница осталась и стала одной фразой — ассистент
# работает с тем, что видит git, и никогда с тем, что git велено игнорировать.

# Сколько строк отдаём за раз и сколько места занимает запись.
ЧТЕНИЕ_СТРОК = 400
НАЙДЕНО_СТРОК = 60
ЗАПИСЬ_БАЙТ = 200_000

# Файлы, которые этот процесс уже писал. Нужны, чтобы вторая правка подряд
# была возможна: без этого правило «не трогать изменённое» запрещало бы
# ассистенту поправить то, что он сам только что положил.
_НАПИСАНО: set[str] = set()


def _доступен(path: str, *, must_exist: bool = True) -> Path:
    """Путь внутри проекта и не в игноре. Иначе — отказ словами."""
    цель = codebase.inside(path, must_exist=must_exist)
    относительный = str(цель.relative_to(codebase.ROOT))
    if codebase.ignored(относительный):
        raise codebase.GitError(
            f"{path} в .gitignore — такие файлы ассистент не трогает. "
            f"Там лежат ключи, базы и модели.")
    return цель


class ПлохойШаблон(ValueError):
    """Шаблон, который Path.match не берёт."""


def _отобрать(файлы: list[str], образец: str) -> list[str]:
    """Сужает список файлов шаблоном. Плохой шаблон — отказ словами.

    Path.match падает ValueError на пустом шаблоне, а «.» пустым и считается.
    Замер дня 34: небольшая модель прислала именно «.», и инструмент ответил
    ей «ОШИБКА ИНСТРУМЕНТА» без причины. Граница должна отказывать словами —
    это общее правило дня, и к шаблону оно относится так же, как к записи.
    """
    try:
        return [ф for ф in файлы if Path(ф).match(образец)]
    except ValueError as err:
        raise ПлохойШаблон(
            f"Шаблон «{образец}» не годится ({err}). Нужен шаблон имени файла: "
            "«*.py», «deploy/*», «static/*.js». Пусто — искать везде.") from err


@server.tool()
async def list_project_files(
    pattern: Annotated[str, Field(
        description="Шаблон вроде «*.py» или «deploy/*», чтобы сузить список. "
                    "Пусто — все файлы проекта.")] = "",
) -> str:
    """Файлы проекта: что вообще есть и где искать.

    Отслеживаемые плюс те, что git не игнорирует. Игнорируемое — ключи, базы,
    модели — в списке не появляется вовсе.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    try:
        файлы = codebase.project_files()
    except codebase.GitError as err:
        return f"git не ответил: {err}"
    if pattern:
        try:
            файлы = _отобрать(файлы, pattern)
        except ПлохойШаблон as err:
            return str(err)
    if not файлы:
        return f"Под «{pattern}» ничего не подошло." if pattern else "Файлов нет."
    return (f"Файлов: {len(файлы)}\n"
            + _обрезать("\n".join(f"  {ф}" for ф in файлы), 120))


@server.tool()
async def read_file(
    path: Annotated[str, Field(description="Путь от корня проекта, например web.py.")],
    from_line: Annotated[int, Field(
        description="С какой строки читать. Нужно, когда файл не влез целиком.")] = 1,
) -> str:
    """Содержимое файла с номерами строк.

    Номера нужны не для красоты: по ним ассистент ссылается на место, и по ним
    же человек это место находит. Длинный файл отдаётся кусками — об обрезке
    сказано прямо, чтобы не выглядело, будто файл кончился.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    try:
        цель = _доступен(path)
    except codebase.GitError as err:
        return f"Не вышло: {err}"
    try:
        строки = цель.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError) as err:
        return f"Не прочитать {path}: {err}"

    начало = max(1, int(from_line or 1))
    кусок = строки[начало - 1:начало - 1 + ЧТЕНИЕ_СТРОК]
    if not кусок:
        return f"{path}: строк всего {len(строки)}, с {начало} читать нечего."
    пронумеровано = "\n".join(f"{начало + n:5}  {с}" for n, с in enumerate(кусок))
    хвост = ""
    if начало - 1 + len(кусок) < len(строки):
        хвост = (f"\n\n… показаны строки {начало}–{начало - 1 + len(кусок)} из "
                 f"{len(строки)}. Дальше — read_file(«{path}», "
                 f"from_line={начало + len(кусок)}).")
    return f"{path}, строк всего {len(строки)}:\n{пронумеровано}{хвост}"


# Знаки, которые в коде почти не встречаются буквально, а в шаблоне — всегда.
# «.» и «*» сюда не входят намеренно: «модуль.функция» и «*.py» — обычные
# буквальные запросы, и предупреждать о них значило бы кричать не по делу.
# Пример здесь нарочно условный, а не настоящее имя из кода: настоящее стало бы
# лишним совпадением для поиска по нему же — см. ниже про замер дня 34.
ЗНАКИ_ШАБЛОНА = ("^", "$", "(?", "[^", ".*", ".+", "\\", "|", "\\d", "\\w")


def _похоже_на_шаблон(query: str) -> str:
    """Приписка к «не найдено», когда запрос похож на регулярное выражение.

    Замер дня 34: небольшая модель передала сюда регулярное выражение на
    строки вида «ключ=значение» — с якорями, классом отрицания и группами —
    и из пустого ответа заключила, что таких строк в .env.example нет. Про
    файл, который не читала. Ответ был правдив о запросе и прочитан как
    правда о файле. Поэтому причина теперь называется вслух.

    Само то выражение здесь не приводится, и это не стеснительность: пример,
    вписанный дословно, стал бы единственным совпадением для запроса, который
    он описывает, — поиск нашёл бы рассказ о неудаче вместо кода. Та же
    ловушка, что с набором вопросов внутри поискового индекса.
    """
    знаки = [з for з in ЗНАКИ_ШАБЛОНА if з in query]
    if not знаки:
        return ""
    return ("\n\nПоиск здесь буквальный: запрос ищется как есть, регулярные "
            f"выражения и шаблоны не разбираются. В запросе есть "
            f"{', '.join(repr(з) for з in знаки)} — если это был шаблон, "
            "повторите обычной подстрокой (например «=» или имя переменной). "
            "О содержимом файла пустой ответ ничего не говорит: чтобы увидеть "
            "строки целиком, прочитайте файл read_file.")


@server.tool()
async def find_in_files(
    query: Annotated[str, Field(
        description="Что искать — подстрока, точно как в тексте.")],
    glob: Annotated[str, Field(
        description="Где искать: «*.py», «deploy/*». Пусто — везде.")] = "",
) -> str:
    """Точный поиск подстроки по файлам проекта: путь, строка, текст.

    Поиск именно точный, а не по смыслу. На вопрос «где используется X» поиск
    по близости даёт НЕКОТОРЫЕ места, и это хуже, чем бесполезно: список
    выглядит полным, не будучи им.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    if not query.strip():
        return "Пустой запрос: нечего искать."
    try:
        файлы = codebase.project_files()
    except codebase.GitError as err:
        return f"git не ответил: {err}"
    if glob:
        try:
            файлы = _отобрать(файлы, glob)
        except ПлохойШаблон as err:
            return str(err)
        if not файлы:
            # Отдельный ответ, а не «ничего не найдено». Причина здесь другая:
            # искать было негде. Со общим ответом модель решила бы, что
            # подстроки в проекте нет, и это был бы ложный вывод.
            return (f"Шаблон «{glob}» не подошёл ни к одному файлу проекта — "
                    f"искать было негде, сам запрос не проверялся. "
                    f"Список файлов покажет list_project_files.")

    находки, где = [], set()
    for ф in файлы:
        try:
            текст = (codebase.ROOT / ф).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue  # двоичное или нечитаемое — не беда поиска
        for n, строка in enumerate(текст.splitlines(), 1):
            if query in строка:
                находки.append(f"  {ф}:{n}  {строка.strip()[:120]}")
                где.add(ф)
    if not находки:
        return ("Точного совпадения нет: "
                f"«{query}» не встречается ни в одном файле проекта."
                + _похоже_на_шаблон(query))
    шапка = f"«{query}» — совпадений {len(находки)} в {len(где)} файлах:"
    return шапка + "\n" + _обрезать("\n".join(находки), НАЙДЕНО_СТРОК)


def _отчёт_о_записи(path: str, относительный: str, что: str) -> str:
    """Что сказать после записи. Общий для цельной записи и точечной замены.

    Отчёт выбирается по тому, в git ли файл, а не по тому, существовал ли.
    Разница не теоретическая: git diff не показывает неотслеживаемое вовсе, и
    для своего же файла, записанного второй раз, пустой diff означал бы
    «ничего не изменилось» — неправда, строки другие.
    """
    try:
        отслеживается = bool(codebase.git("ls-files", "--", относительный).strip())
    except codebase.GitError:
        отслеживается = False
    if not отслеживается:
        строк = len((codebase.ROOT / относительный).read_text(
            encoding="utf-8", errors="replace").splitlines())
        return (f"{что} {path}: строк {строк}. В git его нет — отменяется "
                f"удалением файла, а не git checkout.")
    try:
        diff = codebase.git("diff", "--", относительный)
    except codebase.GitError as err:
        return f"{что} {path}, но diff не показать: {err}"
    if not diff.strip():
        return f"{path} записан, но содержимое не изменилось."
    return (f"{что} {path}. Отменить — git checkout {относительный}\n\n"
            + _обрезать(diff, DIFF_LINES))


def _можно_записать(path: str) -> tuple[Path | None, str, str]:
    """Пускают ли правила дня 34 писать в этот файл.

    Возвращает цель, относительный путь и отказ словами. Общая для цельной
    записи и точечной замены: правила одни и те же, и расходиться им нельзя.
    """
    try:
        цель = _доступен(path, must_exist=False)
    except codebase.GitError as err:
        return None, "", f"Не вышло: {err}"
    относительный = str(цель.relative_to(codebase.ROOT))
    if not цель.exists() or относительный in _НАПИСАНО:
        return цель, относительный, ""
    try:
        состояние = codebase.git("status", "--porcelain", "--", относительный)
    except codebase.GitError as err:
        return None, "", f"git не ответил: {err}"
    отметка = состояние[:2].strip() if состояние.strip() else ""
    if отметка == "??":
        return None, "", (f"{path} существует, но его нет в git — перезаписать "
                          f"нечем будет откатить. Добавьте его в репозиторий "
                          f"или удалите.")
    if отметка:
        return None, "", (f"{path} изменён и не закоммичен ({отметка}). "
                          f"Перезапись затёрла бы вашу работу: git checkout её "
                          f"уже не вернёт. Закоммитьте или откатите файл и "
                          f"повторите.")
    return цель, относительный, ""


@server.tool()
async def replace_in_file(
    path: Annotated[str, Field(description="Путь от корня проекта.")],
    было: Annotated[str, Field(description=(
        "Кусок текста, который надо заменить, — точно как в файле, со "
        "всеми отступами. Должен встречаться в файле ровно один раз."))],
    стало: Annotated[str, Field(description="Чем его заменить.")],
) -> str:
    """Меняет кусок файла на другой. Для правки, а не для переписывания.

    Появился по замеру дня 35, и вот по какому. Субагенту поручили убрать
    дублирование в файле на 482 строки, а записывать он умел только целиком —
    и принялся восстанавливать весь файл по кускам. Кругов не хватило, файл
    оборвался на середине, ворота его не пустили. Цельная запись годится для
    нового файла и для короткого; правка большого ею не делается.

    Требование «ровно один раз» — не придирка. Кусок, встречающийся дважды,
    означает, что модель не знает, какой из них правит; молча взять первый —
    это тихая порча второго.

    Границы те же, что у write_file: внутри корня, git не игнорирует, чужую
    незакоммиченную работу не трогаем.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    if not было:
        return "Пустой «было»: нечего заменять. Для нового файла — write_file."
    цель, относительный, отказ = _можно_записать(path)
    if отказ:
        return отказ
    if not цель.exists():
        return (f"{path} не существует. Точечная замена правит то, что есть; "
                f"новый файл заводится write_file.")
    try:
        текст = цель.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as err:
        return f"Не прочитать {path}: {err}"
    сколько = текст.count(было)
    if сколько == 0:
        return (f"В {path} такого куска нет — ни одного совпадения. Замена "
                f"точная, посимвольная: сверьте отступы и пробелы, прочитав "
                f"файл read_file.")
    if сколько > 1:
        return (f"В {path} этот кусок встречается {сколько} раза — непонятно, "
                f"какой править. Возьмите кусок подлиннее, чтобы он стал "
                f"единственным.")
    # Предел здесь на кусок, а не на файл, и это не послабление. ЗАПИСЬ_БАЙТ
    # ограничивает то, что модель печатает: у write_file это весь файл, у
    # замены — только заменяемое. Мерить файл было бы прямо против смысла
    # инструмента: README весит 229 КБ, и правка в одну строку оказалась бы
    # запрещена именно там, где точечная замена и нужна.
    if len(стало.encode("utf-8")) > ЗАПИСЬ_БАЙТ:
        return f"Слишком большой кусок: предел {ЗАПИСЬ_БАЙТ // 1024} КБ."
    новый = текст.replace(было, стало, 1)
    try:
        цель.write_text(новый, encoding="utf-8")
    except OSError as err:
        return f"Не записать {path}: {err}"
    _НАПИСАНО.add(относительный)
    return _отчёт_о_записи(path, относительный, "Правлен")


@server.tool()
async def write_file(
    path: Annotated[str, Field(description="Путь от корня проекта.")],
    content: Annotated[str, Field(
        description="Новое содержимое файла ЦЕЛИКОМ, а не кусок.")],
) -> str:
    """Пишет файл и показывает, что изменилось.

    Страховка — сам git: правка видна в `git diff`, отменяется
    `git checkout <файл>`. Отсюда главное правило: там, где git не сможет
    откатить, мы не перезаписываем. Поэтому файл с незакоммиченными правками
    и существующий файл вне git остаются нетронутыми, а новый создать можно.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    if len(content.encode("utf-8")) > ЗАПИСЬ_БАЙТ:
        return f"Слишком большой файл: предел {ЗАПИСЬ_БАЙТ // 1024} КБ."
    цель, относительный, отказ = _можно_записать(path)
    if отказ:
        return отказ
    существовал = цель.exists()
    try:
        цель.parent.mkdir(parents=True, exist_ok=True)
        цель.write_text(content, encoding="utf-8")
    except OSError as err:
        return f"Не записать {path}: {err}"
    _НАПИСАНО.add(относительный)

    return _отчёт_о_записи(path, относительный,
                           "Создан" if not существовал else "Записан")


@server.tool()
async def run_checks() -> str:
    """Прогоняет проверки проекта и возвращает их вывод.

    Аргументов нет, и это не упущение. Инструмент, принимающий команду, был бы
    «выполни что угодно», а здесь набор зафиксирован кодом в checks.py: модель
    решает, когда проверить, но не что запустить. Граница дня 34 остаётся той
    же.

    Проверки идут в рабочем дереве этого сервера (PROJECT_ROOT), то есть у
    каждого субагента в своём, и чужую работу увидеть нельзя.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    try:
        файлы = codebase.project_files()
    except codebase.GitError:
        файлы = []
    _, отчёт = await asyncio.to_thread(checks.прогнать, codebase.ROOT, файлы)
    return отчёт


