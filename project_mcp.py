"""Сервер MCP про сам репозиторий: ветка, изменённое, diff, коммиты.

Первый наш инструмент, запускающий внешнюю программу, поэтому про границы
стоит сказать прямо. Корень фиксирован переменной `PROJECT_ROOT`, а не
приходит от модели: иначе инструмент читал бы любой репозиторий на машине.
Подкоманды git — из списка в codebase.ALLOWED, то есть `push` в нём нет даже
теоретически. Аргументы передаются списком, без shell. И здесь нет
инструмента «прочитай файл»: содержимое проекта доступно через поиск по
индексу, а такой инструмент означал бы чтение чего угодно по просьбе модели.

Сервер локальный по устройству. На сервере приложения истории нет вовсе — код
кладётся `git archive`'ом, без .git, — и там все четыре инструмента честно
скажут, что репозитория не видят. Поэтому юнита для него нет: служба, которая
ничего не может ответить, памяти стоит столько же, сколько рабочая.

    uvicorn project_mcp:app --host 127.0.0.1 --port 8004
"""

from typing import Annotated

from mcp.server.mcpserver import MCPServer
from pydantic import Field

import codebase

# Сколько строк diff отдаём. Предел не из осторожности, а из арифметики: diff
# на тысячу строк — это около десяти тысяч токенов, то есть окно контекста
# местной модели целиком, и минута разбора на процессоре (замер дня 29 —
# 13 с на тысячу токенов).
DIFF_LINES = 400

# Сколько коммитов максимум, сколько бы ни попросили.
COMMITS_MAX = 50

server = MCPServer(
    name="Проект: git и состояние репозитория",
    version="1.0.0",
    instructions=(
        "Состояние репозитория, над которым идёт работа: текущая ветка, "
        "изменённые файлы, diff рабочего каталога, последние коммиты. "
        "Содержимое файлов этими инструментами не читается — для него есть "
        "поиск по подключённым наборам документов проекта. Если репозитория "
        "нет, инструменты скажут об этом словами."
    ),
)


def _обрезать(текст: str, предел: int) -> str:
    """Отдаёт не больше предела строк и говорит, сколько осталось за краем."""
    строки = текст.splitlines()
    if len(строки) <= предел:
        return текст.rstrip()
    хвост = len(строки) - предел
    return "\n".join(строки[:предел]) + f"\n… ещё {хвост} строк, здесь не показаны"


def _нет_репозитория() -> str:
    return (f"В {codebase.ROOT} нет git-репозитория, поэтому про ветку, "
            f"изменения и коммиты сказать нечего. Так и бывает на сервере: "
            f"код там кладётся git archive'ом, без истории.")


@server.tool()
async def git_branch() -> str:
    """Текущая ветка репозитория и насколько она расходится с origin.

    Отвечает на вопрос «где я сейчас»: имя ветки, последний коммит и сколько
    коммитов она опережает или отстаёт от своей удалённой пары.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    try:
        ветка = codebase.git("rev-parse", "--abbrev-ref", "HEAD").strip()
        последний = codebase.git("log", "-1", "--format=%h %s").strip()
    except codebase.GitError as err:
        return f"git не ответил: {err}"

    расхождение = ""
    try:
        # Пары может не быть вовсе — у новой ветки её нет, и это не ошибка.
        счёт = codebase.git("rev-list", "--left-right", "--count",
                            f"{ветка}...origin/{ветка}")
    except codebase.GitError:
        расхождение = ", удалённой пары нет"
    else:
        впереди, позади = (счёт.split() + ["0", "0"])[:2]
        if впереди != "0" or позади != "0":
            расхождение = f", впереди origin на {впереди}, позади на {позади}"
        else:
            расхождение = ", совпадает с origin"
    return f"Ветка {ветка}{расхождение}. Последний коммит: {последний}"


@server.tool()
async def changed_files() -> str:
    """Какие файлы изменены в рабочем каталоге и что уже добавлено в индекс.

    Нужно, чтобы говорить о текущей работе, а не о последнем коммите: правка,
    которую ещё не закоммитили, в истории не видна.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    try:
        отметки = codebase.git("status", "--porcelain").splitlines()
    except codebase.GitError as err:
        return f"git не ответил: {err}"
    if not отметки:
        return "Рабочий каталог чист: незакоммиченных правок нет."

    # Первые две буквы строки status: слева индекс, справа рабочий каталог.
    словами = {"M": "изменён", "A": "добавлен", "D": "удалён", "R": "переименован",
               "C": "скопирован", "?": "не отслеживается", "!": "игнорируется"}
    строки = []
    for отметка in отметки:
        код, путь = отметка[:2], отметка[3:]
        if код in ("??", "!!"):
            # Обе буквы одинаковые, и «в индексе не отслеживается, в каталоге
            # не отслеживается» — это одно и то же сказанное дважды.
            строки.append(f"  {путь} — {словами[код[0]]}")
            continue
        где = []
        if код[0].strip():
            где.append(f"в индексе {словами.get(код[0], код[0])}")
        if код[1].strip():
            где.append(f"в каталоге {словами.get(код[1], код[1])}")
        строки.append(f"  {путь} — {', '.join(где) or код}")
    return f"Изменённых файлов {len(отметки)}:\n" + _обрезать("\n".join(строки), 60)


@server.tool()
async def git_diff(
    path: Annotated[str, Field(
        description="Файл или папка внутри проекта, чтобы сузить diff. "
                    "Пусто — весь рабочий каталог.")] = "",
    staged: Annotated[bool, Field(
        description="True — показать добавленное в индекс (git diff --staged) "
                    "вместо незакоммиченного в рабочем каталоге.")] = False,
) -> str:
    """Diff рабочего каталога: что именно изменилось в коде.

    Вывод обрезается — очень большой diff в запрос не влезет, и об обрезке
    будет сказано в самом ответе.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    аргументы = ["diff"]
    if staged:
        аргументы.append("--staged")
    try:
        if path:
            # Путь от модели проверяем: внутрь корня и не дальше.
            цель = codebase.inside(path)
            аргументы += ["--", str(цель.relative_to(codebase.ROOT))]
        текст = codebase.git(*аргументы)
    except codebase.GitError as err:
        return f"Не вышло: {err}"
    if not текст.strip():
        где = "в индексе" if staged else "в рабочем каталоге"
        return f"Пусто: {где}" + (f" по пути {path}" if path else "") + " изменений нет."
    return _обрезать(текст, DIFF_LINES)


@server.tool()
async def recent_commits(
    limit: Annotated[int, Field(
        description="Сколько последних коммитов показать, 1–50.")] = 10,
) -> str:
    """Последние коммиты: что в проекте делали в последнее время.

    По одной строке на коммит — хеш, дата, автор и заголовок.
    """
    if not codebase.is_repo():
        return _нет_репозитория()
    сколько = max(1, min(int(limit or 10), COMMITS_MAX))
    try:
        текст = codebase.git(
            "log", f"-{сколько}", "--date=short", "--format=%h %ad %an: %s")
    except codebase.GitError as err:
        return f"git не ответил: {err}"
    return текст.rstrip() or "В репозитории нет коммитов."


# Приложение для uvicorn. Путь /mcp — тот же, по которому клиент ходит к
# чужим серверам: адрес получается однородным.
app = server.streamable_http_app(streamable_http_path="/mcp")
