def прочитать(path: str) -> list[tuple[str, list[str]]]:
    """Вопросы из файла: «вопрос | ожидание / ещё одно ожидание».

    Ожиданий может быть несколько через косую черту, и годится любое. Без этого
    замер врал: на вопрос про оклад модель отвечала то «сорок шесть рублей», то
    «46 рублей» — ответ верный оба раза, а проверка по одной подстроке половину
    таких ответов записывала в промахи.
    """
    вопросы = []
    for строка in open(path, encoding="utf-8"):
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        вопрос, _, ожидание = строка.partition("|")
        if вопрос.strip():
            варианты = [o.strip().lower() for o in ожидание.split("/") if o.strip()]
            вопросы.append((вопрос.strip(), варианты))
    return вопросы


# Как называется процесс, который держит веса. Имён два, потому что Ollama
# меняла устройство: раньше это был «ollama runner», в 0.40 — отдельный бинарник
# llama-server. Ищем по обоим, иначе замер памяти молча показывает ноль.
RUNNER = r"llama-server|ollama runner"


def память() -> int:
    """Сколько мегабайт держат процессы, которые считают модель.

    Это не весь расход Ollama: сервер и runner — разные процессы, и веса живут
    во втором (замер: сервер 28 МБ, runner 2,4 ГБ на qwen2.5:3b q4_K_M). Берём
    сумму по всем runner'ам — когда рядом стоит вторая модель, их два, и
    показать один значило бы занизить вдвое.
    """
    try:
        pids = subprocess.run(["pgrep", "-f", RUNNER],
                              capture_output=True, text=True, timeout=5).stdout.split()
        if not pids:
            return 0
        ps = subprocess.run(["ps", "-o", "rss=", "-p", ",".join(pids)],
                            capture_output=True, text=True, timeout=5).stdout
        return sum(int(x) for x in ps.split()) // 1024
    except (OSError, ValueError, subprocess.SubprocessError):
        return 0


async def найти(вопрос: str, настройка: Настройка, chat_id: int,
                pool: int) -> tuple[list[dict], str, list[str]]:
    """Поиск по документам ровно так, как его делает search_docs.

    Возвращает выдержки, пояснение судьи и список запросов — последние два
    нужны шапке, которую увидит модель.
    """
    запросы = [вопрос]
    if настройка.rewrite:
        запросы = await research_mcp.rewrite_query(вопрос)
    found = await asyncio.to_thread(rag.search_collections, запросы, chat_id, pool)
    found = await asyncio.to_thread(rag.keep_wordy, found, запросы)
    found = await asyncio.to_thread(rag.merge_neighbours, found)
    отбор = ""
    if настройка.judge:
        found, отбор = await research_mcp.judge_hits(вопрос, found)
    return found, отбор, запросы


def собрать(вопрос: str, выдержки: list[dict], отбор: str, запросы: list[str],
            история: list[dict], настройка: Настройка,
            схемы: list[dict]) -> list[dict]:
    """Запрос в том порядке, в каком его складывает приложение.

    Порядок не произволен: блок выдержек стоит вплотную к вопросу, а не в
    начале вместе с системными. Так в web.py (`plan.messages[-1:-1]`), и так
    проверено — блок в начале проигрывает свежей истории.
    """
    сообщения = [{"role": "system", "content": настройка.system or llm.SYSTEM_PROMPT}]
    if схемы:
        сообщения += mcp_tools.blocks(схемы)
    # Контекст: прошлые реплики, сколько их просит настройка. Последнее место
    # занимает сам вопрос, поэтому из истории берём на одно меньше.
    if настройка.context > 1 and история:
        сообщения += история[-(настройка.context - 1):]
    # Правила инструмента подставляем сами, а не флагом format_hits: модуль
    # выбирает их по адресу модели, а колонке «до» нужны именно полные — те,
    # с которыми приложение жило до дня 29.
    найдено = research_mcp.format_hits(выдержки, queries=запросы, отбор=отбор,
                                       rules=False)
    правила = {"full": research_mcp.ANSWER_RULES_FULL,
               "terse": research_mcp.ANSWER_RULES_TERSE}.get(настройка.rules, "")
    if правила:
        найдено += "\n" + правила
    сообщения.append({"role": "system",
                      "content": rag.excerpts_block(найдено, terse=настройка.terse)})
    сообщения.append({"role": "user", "content": вопрос})
    return сообщения


async def спросить(сообщения: list[dict], настройка: Настройка,
                   схемы: list[dict]) -> dict:
    """Один вызов модели потоком. Время делим на разбор и генерацию.

    Поток нужен именно для этого деления: до первого куска модель читает
    запрос, после — пишет ответ. На CPU это два совершенно разных расхода, и
    одна общая цифра скрыла бы, за что мы платим.
    """
    началось = time.monotonic()
    первый = None
    ответ, вызовы, usage, причина = "", [], {}, "unknown"
    async for событие in llm.stream(
            сообщения, model=настройка.model or None, thinking=False,
            max_tokens=настройка.max_tokens, temperature=настройка.temperature,
            seed=настройка.seed, tools=схемы or None):
        if событие["type"] in ("content", "reasoning"):
            if первый is None:
                первый = time.monotonic() - началось
            if событие["type"] == "content":
                ответ += событие["text"]
        elif событие["type"] == "done":
            usage = событие.get("usage") or {}
            вызовы = событие.get("tool_calls") or []
            причина = событие["finish_reason"]
    всего = time.monotonic() - началось
    # Модель могла не сказать ни слова — только позвать инструмент. Тогда
    # «время до первого куска» это всё время целиком: разбор и был работой.
    разбор = всего if первый is None else первый
    return {
        "текст": ответ,
        "вызовы": [c.get("function", {}).get("name", "?") for c in вызовы],
        "разбор": разбор,
        "генерация": max(0.0, всего - разбор),
        "всего": всего,
        "запрос_токенов": usage.get("prompt_tokens", 0),
        "ответ_токенов": usage.get("completion_tokens", 0),
        "обрыв": причина == "length",
    }


async def прогон(вопрос: str, ожидания: list[str], настройка: Настройка, *,
                 chat_id: int, pool: int, история: list[dict],
                 кэш: dict, схемы: list[dict]) -> dict:
    """Один вопрос с одной настройкой. Возвращает замеры этого хода."""
    # Поиск и судья от большинства ручек не зависят — считаем раз и помним.
    ключ = (вопрос, настройка.rewrite, настройка.judge, pool)
    if ключ not in кэш:
        t = time.monotonic()
        кэш[ключ] = (*await найти(вопрос, настройка, chat_id, pool),
                     time.monotonic() - t)
    найдено, отбор, запросы, поиск = кэш[ключ]
    выдержки = найдено[:настройка.chunks]
    if not выдержки:
        return {"выдержек": 0, "эталон": False, "ожидание": False, "поиск": поиск,
                "разбор": 0.0, "генерация": 0.0, "всего": поиск, "цитат": 0,
                "сверено": 0, "источник": False, "вызовы": [], "обрыв": False,
                "запрос_токенов": 0, "ответ_токенов": 0,
                "текст": "(выдержек не осталось)"}

    сообщения = собрать(вопрос, выдержки, отбор, запросы, история, настройка,
                        схемы if настройка.tools else [])
    try:
        итог = await спросить(сообщения, настройка, схемы if настройка.tools else [])
    except llm.LLMError as err:
        итог = {"текст": f"(ошибка: {err})", "вызовы": [], "разбор": 0.0,
                "генерация": 0.0, "всего": 0.0, "запрос_токенов": 0,
                "ответ_токенов": 0, "обрыв": False}

    опора = grounding.check(итог["текст"], выдержки)
    return {
        **итог,
        "поиск": поиск,
        "выдержек": len(выдержки),
        "оценка_токенов": tokens_mod.estimate_messages(сообщения),
        # Эталон — дошла ли до модели выдержка, в которой ответ есть вообще.
        # Без него промах не отличить от «поиск не нашёл».
        "эталон": any(o in h["text"].lower() for o in ожидания for h in выдержки),
        "ожидание": any(o in итог["текст"].lower() for o in ожидания),
        "цитат": опора.get("quotes", 0),
        "сверено": опора.get("verified", 0),
        "источник": bool(опора.get("named")),
    }


async def схемы_серверов() -> list[dict]:
    """Схемы инструментов с работающих серверов MCP — как их видит модель.

    Собираем через те же request_tools, что и приложение: составные имена
    («pogoda__forecast») получаются из названия сервера, а небольшая модель
    выбирает инструмент именно по имени. Похожие схемы здесь не годятся.
    """
    строки = []
    for номер, название, адрес in СЕРВЕРЫ:
        try:
            сервер = await mcp_tools.list_tools(адрес)
        except mcp_tools.MCPError as err:
            print(f"  сервер «{название}» недоступен: {err}", file=sys.stderr)
            continue
        строки.append({"id": номер, "title": название, "url": адрес,
                       "tools": mcp_tools.tools_json(сервер)})
    схемы, _ = mcp_tools.request_tools(строки)
    return схемы


ЗАГОЛОВОК = (f"{'вопрос':34} {'выд':>4} {'этал':>5} {'ожид':>5} {'цит':>6} "
             f"{'ист':>4} {'запрос':>7} {'поиск':>6} {'разбор':>7} "
             f"{'генер':>6} {'всего':>6}")


def строка(вопрос: str, r: dict) -> str:
    return (f"{вопрос[:34]:34} {r['выдержек']:>4} {str(r['эталон'])[:3]:>5} "
            f"{str(r['ожидание'])[:3]:>5} {r['цитат']}/{r['сверено']:<4} "
            f"{str(r['источник'])[:3]:>4} {r['запрос_токенов']:>7} "
            f"{r['поиск']:>6.1f} {r['разбор']:>7.1f} {r['генерация']:>6.1f} "
            f"{r['поиск'] + r['всего']:>6.1f}")


def итоги(название: str, собрано: list[dict]) -> None:
    """Сводка по одному положению ручки."""
    if not собрано:
        print(f"  {название}: нет замеров")
        return
    n = len(собрано)
    сек = sum(r["поиск"] + r["всего"] for r in собрано) / n
    скорость = [r["ответ_токенов"] / r["генерация"]
                for r in собрано if r["генерация"] > 0.5 and r["ответ_токенов"]]
    вызовов = sum(len(r["вызовы"]) for r in собрано)
    print(f"  {название:18} ожидание {sum(r['ожидание'] for r in собрано)}/{n}"
          f" · источник {sum(r['источник'] for r in собрано)}/{n}"
          f" · цитаты сверены {sum(r['цитат'] == r['сверено'] and r['цитат'] > 0 for r in собрано)}/{n}"
          f" · запрос ~{round(sum(r['запрос_токенов'] for r in собрано) / n)} токенов"
          f" · {сек:.1f} с на вопрос"
          + (f" · {sum(скорость) / len(скорость):.1f} токенов/с" if скорость else "")
          + (f" · вызовов инструментов {вызовов}" if вызовов else "")
          + (f" · обрывов по лимиту {sum(r['обрыв'] for r in собрано)}"
             if any(r["обрыв"] for r in собрано) else ""))


async def прокрутить(вопросы: list[tuple[str, str]], варианты: list[tuple[str, Настройка]],
                     *, chat_id: int, pool: int, повторов: int, подробно: bool) -> None:
    """Все вопросы на каждом положении ручки."""
    схемы = await схемы_серверов()
    print(f"схем инструментов собрано: {len(схемы)}")
    кэш: dict = {}
    сводка: list[tuple[str, list[dict]]] = []

    for название, настройка in варианты:
        модель = настройка.model or llm.MODEL
        print(f"\n########## {название} · {модель} · {llm.BASE_URL}")
        print(f"  память до прогона: {память()} МБ")
        print(ЗАГОЛОВОК)
        собрано: list[dict] = []
        история: list[dict] = []
        for вопрос, ожидания in вопросы:
            for _ in range(повторов):
                try:
                    r = await прогон(вопрос, ожидания, настройка, chat_id=chat_id,
                                     pool=pool, история=история, кэш=кэш, схемы=схемы)
                except Exception as err:  # noqa: BLE001 — один вопрос не рушит замер
                    print(f"{вопрос[:34]:34} ОШИБКА: {type(err).__name__}: {err}")
                    continue
                собрано.append(r)
                print(строка(вопрос, r))
                if подробно:
                    print(f"    {r['текст'][:300]}")
                    if r["вызовы"]:
                        print(f"    вызвала: {', '.join(r['вызовы'])}")
            # История растёт настоящими репликами этого же прогона: выдумывать
            # переписку, чтобы замерить цену контекста, незачем.
            if собрано:
                история += [{"role": "user", "content": вопрос},
                            {"role": "assistant", "content": собрано[-1]["текст"]}]
        print(f"  память после прогона: {память()} МБ")
        сводка.append((название, собрано))

    print("\n########## сводка")
    for название, собрано in сводка:
        итоги(название, собрано)


def main() -> None:
    разбор = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    разбор.add_argument("вопросы", help="файл со строками «вопрос | ожидание»")
    разбор.add_argument("--chat", type=int, default=900,
                        help="диалог, к которому подключён набор")
    разбор.add_argument("--pool", type=int, default=30, help="кусков до отбора")
    разбор.add_argument("--knob", choices=sorted(РУЧКИ), help="какую ручку крутим")
    разбор.add_argument("--values", help="значения через запятую")
    разбор.add_argument("--compare", action="store_true",
                        help="две колонки: как было до дня 29 и как стало")
    разбор.add_argument("--repeat", type=int, default=1,
                        help="повторов на вопрос (разброс виден только на повторах)")
    разбор.add_argument("--verbose", action="store_true", help="печатать ответы")
    дано = разбор.parse_args()

    if not дано.compare and not дано.knob:
        sys.exit("Нужно --compare или --knob с --values")
    if дано.knob and not дано.values:
        sys.exit(f"--knob {дано.knob} без --values: нечего сравнивать")

    вопросы = прочитать(дано.вопросы)
    if not вопросы:
        sys.exit("В файле нет вопросов")
    if not rag.attached_collections(дано.chat):
        sys.exit(f"К диалогу {дано.chat} не подключён ни один набор. "
                 f"Подключите: python -c \"import rag; rag.attach({дано.chat}, <id>, True)\"")
    if not llm.is_local(llm.BASE_URL):
        print(f"Внимание: {llm.BASE_URL} — не локальный адрес. Замер пойдёт в "
              f"облако, и числа будут не про эту машину.", file=sys.stderr)

    if дано.compare:
        варианты = [("до дня 29", ДО), ("после", ПОСЛЕ)]
    else:
        читать = РУЧКИ[дано.knob]
        варианты = [(f"{дано.knob}={v}", replace(ПОСЛЕ, **{дано.knob: читать(v)}))
                    for v in дано.values.split(",")]

    asyncio.run(прокрутить(вопросы, варианты, chat_id=дано.chat, pool=дано.pool,
                           повторов=max(1, дано.repeat), подробно=дано.verbose))


if __name__ == "__main__":
    main()
