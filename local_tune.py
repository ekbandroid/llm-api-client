"""Одна ручка за прогон: что на местной модели покупает секунды, а что качество.

Машина решает здесь больше, чем настройки. На Intel без Metal Ollama считает
на процессоре, и разбор запроса идёт около 6,5 с на каждую тысячу токенов
(замер в llm.py). Значит, всякая тысяча, которую мы не отправили, — это шесть
с половиной сэкономленных секунд, и наоборот: «добавим контекста, пусть лучше
понимает» стоит не памяти, а минут ожидания.

Поэтому скрипт крутит **по одной ручке за прогон** и показывает обе стороны
сделки — качество и время — рядом, в одной таблице:

    python local_tune.py вопросы.txt --compare
    python local_tune.py вопросы.txt --knob chunks --values 2,3,4,6
    python local_tune.py вопросы.txt --knob tools --values off,on --repeat 3

`--compare` — две колонки, «до» и «после»: настройки, с которыми приложение
жило до дня 29, против набора LOCAL_PRESET из web.py.

Запрос собирается в той форме, в какой его собирает приложение, и это
принципиально: день 28 показал, что обвязка решает не меньше выдержек. Берётся
настоящий индекс (rag), настоящие схемы инструментов с работающих серверов MCP
(mcp_tools), тот же текст выдержек (research_mcp.format_hits) и тот же блок
правил (rag.excerpts_block). Приложение целиком сюда не тащится — ни FastAPI,
ни базы переписки не нужно.

Вопросы берутся из файла, а не из кода: они описывают содержимое чужих
документов. Формат — строка на вопрос, слева вопрос, справа подстрока, которая
должна оказаться в ответе:

    какая зарплата у Александра Ивановича? | сорок шесть

О времени. Один ответ местной модели — десятки секунд, а судья над выдержками
один стоит около полутора минут. Поиск и судью скрипт считает один раз на
вопрос и переиспользует для всех значений ручки, если ручка их не меняет, —
иначе прогон из шести вопросов и четырёх значений шёл бы час с лишним.

И оговорка, без которой числа времени читаются неверно. llama-server помнит
разобранный префикс запроса, и повторный прогон той же настройки даёт «разбор
0,2 с» вместо пятидесяти — это попадание в кэш, а не заслуга настройки.
Поэтому сравнивать время стоит в пределах одного прогона и по значениям,
которые меняют текст запроса; подозрительно малый разбор при большом
«запрос токенов» — всегда кэш. Качество (эталон, ожидание, опора) кэш не
затрагивает вовсе.
"""

