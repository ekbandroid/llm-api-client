@dataclass(frozen=True)
class Настройка:
    """Всё, что день 29 умеет повернуть. Поля — ручки, значения — положения."""

    temperature: float | None = 0.2
    chunks: int = 4
    context: int = 1          # сколько прошлых сообщений идёт в запрос
    tools: bool = False       # кладём ли схемы инструментов MCP
    terse: bool = True        # короткий вариант правил блока выдержек
    rules: str = "terse"      # хвост правил инструмента: full | terse | нет
    judge: bool = False       # отбор выдержек судьёй
    rewrite: bool = True      # переписывание вопроса перед поиском
    system: str = ""          # пусто — взять llm.SYSTEM_PROMPT
    model: str = ""           # пусто — взять llm.MODEL
    max_tokens: int | None = 600
    seed: int | None = 7


