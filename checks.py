"""Ворота: что должно пройти, чтобы работу можно было отдавать.

Отдельный модуль, а не функция внутри сервера инструментов, потому что
зовущих двое и роли у них разные.

Субагент зовёт ворота через инструмент `run_checks`, чтобы чинить себя на
ходу: написал — проверил — не прошло — правит. Пайплайн зовёт их сам перед
тем, как пустить работу в репозиторий, и его вызов решающий. Верить отчёту
субагента здесь нельзя: отчёт пишет модель, а пускать наружу должен код.
Замер дня 34 показал, чем кончается доверие — небольшая модель заключила,
что в .env.example нет строк «ключ=значение», не открыв файла.

Набор проверок повторяет шаги run-local.sh: то же, что человек гоняет перед
коммитом. Пополняется он правкой этого файла, а не просьбой в чат, — в этом
всё свойство: модель решает, *когда* проверить, но не *что* запустить.

Запускается всё в указанном корне, поэтому и скрипты берутся оттуда же:
ворота проверяют ту ветку, которая поедет в PR, вместе с её собственными
проверками, а не с теми, что лежат у зовущего.
"""

import subprocess
import sys
import time
from pathlib import Path

# Сколько строк вывода неудачной проверки показываем.
ОТЧЁТА_СТРОК = 80
ПРОВЕРКА_СЕКУНД = 300

ПРОШЛИ = "Все проверки прошли."
НЕ_ПРОШЛИ = "Проверки НЕ прошли — работа не готова, читайте вывод и правьте."


def список(корень: Path, файлы: list[str]) -> list[tuple[str, list[str]]]:
    """Что запускаем и под каким именем это показать.

    Питон берётся свой же (sys.executable): рабочее дерево git — это только
    файлы под версией, венва в нём нет и быть не может, он в .gitignore.
    Поэтому проверки зовут интерпретатор того процесса, который их исполняет.
    """
    пи = sys.executable
    шаг = [
        ("синтаксис питона",
         [пи, "-m", "compileall", "-q", "-x",
          r"(\.venv|__pycache__|local-data)", "."]),
        ("юнит-тесты", [пи, "-m", "unittest", "discover", "-v"]),
    ]
    for скрипт, имя in (("deploy/check-js.py", "разбор javascript"),
                        ("deploy/check-workflow.py", "разбор заданий GitHub")):
        if (корень / скрипт).exists():
            шаг.append((имя, [пи, скрипт]))
    если_шелл = [ф for ф in файлы if ф.endswith(".sh")]
    if если_шелл:
        шаг.append(("разбор shell", ["sh", "-n", *если_шелл]))
    return шаг


def прогнать(корень: Path, файлы: list[str]) -> tuple[bool, str]:
    """Гоняет весь набор и возвращает «прошло ли» и отчёт для человека."""
    итог, всё_прошло = [], True
    for имя, команда in список(корень, файлы):
        начало = time.monotonic()
        try:
            # errors="replace" здесь обязателен, и это не перестраховка.
            # Нашло ревью дня 32 на PR, который открыл пайплайн дня 35, —
            # проверено опытом: text=True берёт кодировку локали со строгим
            # разбором, и первый же негодный байт из проверяемого кода роняет
            # UnicodeDecodeError. Он не ValueError для TimeoutExpired и не
            # OSError, то есть не ловится ничем ниже, и падает весь прогон
            # ворот — вместо того чтобы показать вывод с подпорченным знаком.
            готово = subprocess.run(команда, cwd=корень, capture_output=True,
                                    text=True, encoding="utf-8",
                                    errors="replace", timeout=ПРОВЕРКА_СЕКУНД)
        except subprocess.TimeoutExpired:
            всё_прошло = False
            итог.append(f"⨯ {имя}: не уложилась в {ПРОВЕРКА_СЕКУНД} с")
            continue
        except OSError as err:
            всё_прошло = False
            итог.append(f"⨯ {имя}: не запустилась ({err})")
            continue
        секунд = time.monotonic() - начало
        вывод = (готово.stdout + готово.stderr).strip()
        if готово.returncode == 0 or _пусто_а_не_поломка(имя, готово.returncode):
            итог.append(f"✓ {имя} — {секунд:.1f} с{_о_тестах(имя, вывод)}")
            continue
        всё_прошло = False
        итог.append(f"⨯ {имя} — код возврата {готово.returncode}\n"
                    + _обрезать(вывод or "(вывод пуст)", ОТЧЁТА_СТРОК))
    шапка = ПРОШЛИ if всё_прошло else НЕ_ПРОШЛИ
    return всё_прошло, шапка + "\n\n" + "\n".join(итог)


def _пусто_а_не_поломка(имя: str, код: int) -> bool:
    """Отсутствие тестов — не провал ворот.

    `unittest discover` отвечает кодом 5, когда не нашёл ни одного теста.
    Считать это провалом нельзя: задача про рефакторинг ветвится от master,
    где тестов ещё нет, и ворота резали бы работу, к которой у них претензий
    нет. Ворота отвечают на «не сломалось ли», а не на «написан ли тест» —
    второе спрашивают с того, кому это поручено, и приписка _о_тестах ему об
    этом прямо говорит.
    """
    return имя == "юнит-тесты" and код == 5


def _о_тестах(имя: str, вывод: str) -> str:
    """Приписка к пройденным тестам: сколько их было.

    Без неё ворота врут молчанием. Пустой прогон выглядел бы как успех, и
    агент, которому поручено написать тест, счёл бы задачу выполненной, не
    написав ничего.
    """
    if имя != "юнит-тесты":
        return ""
    if "NO TESTS RAN" in вывод or "Ran 0 tests" in вывод:
        return ": тестов не найдено ни одного (это не успех, а пустой прогон)"
    for строка in вывод.splitlines():
        if строка.startswith("Ran ") and "test" in строка:
            return f": {строка.strip()}"
    return ""


def _обрезать(текст: str, предел: int) -> str:
    строки = текст.splitlines()
    if len(строки) <= предел:
        return текст.rstrip()
    return ("\n".join(строки[:предел])
            + f"\n… ещё {len(строки) - предел} строк, здесь не показаны")
