def _project(цель: str) -> Условия:
    """`/project <цель>` — работа с файлами, а не разговор о них."""
    if not цель:
        return Условия(name="project", answer=PROJECT_TEXT)
    return Условия(
        name="project",
        question=цель,
        # Наборы документов не подключаем намеренно. На «найди все места»
        # выдержки по близости дают НЕКОТОРЫЕ места, и это хуже, чем
        # бесполезно: список выглядит полным, не будучи им. Здесь нужен
        # точный ответ, а он — из инструментов.
        tools_allowed=("list_project_files", "read_file", "find_in_files",
                       "write_file", "git_branch", "changed_files", "git_diff",
                       "recent_commits"),
        # Больше общего предела, и не на вкус. «Сверь .env.example с кодом»
        # уложилось в шесть кругов ровно до записи: обзор прошёл, файл не
        # записан, ответ оборван предохранителем. Обзор — работа, где число
        # файлов заранее неизвестно: сколько ни возьми, цель вида «сверь всё»
        # упрётся. Двенадцать — чтобы за осмотром осталось место на правку и
        # на рассказ о ней; предохранителем это быть не перестаёт.
        rounds=12,
        system=PROJECT_SYSTEM,
    )


