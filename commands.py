"""Команды чата: строка, начинающаяся со слеша, меняет условия одного хода.

Зачем реестр, а не один `if` в обработчике. Команда — это не текст вопроса, а
набор условий, при которых на вопрос отвечают: какие наборы документов
подключены, в каком режиме идёт поиск, какие инструменты лежат в запросе.
Таких наборов условий будет больше одного (день 32 добавит ревью кода), и
место, где они перечислены, должно быть одно.

Условия задаются **на один ход**. Диалог от команды не превращается
необратимо в «ассистента разработчика»: следующий вопрос без слеша пойдёт
обычным путём, и это видно по тому, что в запросе нет блока про проект.
Исключение — подключение наборов: оно постоянное и намеренно видимое, во
вкладке «Документы» появится отметка. Прятать от человека, что к его диалогу
прицепили двести килобайт README, нельзя.
"""

from dataclasses import dataclass, field

import codebase
import db

# Приставка, по которой строка считается командой. Пробел после неё не нужен:
# «/help» без вопроса — тоже команда, и у неё свой ответ.
PREFIX = "/"


@dataclass
class Условия:
    """Чем ход по команде отличается от обычного.

    question — текст, который увидит модель вместо исходной строки с командой.
    Пустой означает, что обращаться к модели не нужно вовсе: ответ готов.
    """

    name: str
    question: str = ""
    answer: str = ""
    rag_mode: str = ""
    rag_pool: int = 0
    attach_titles: tuple[str, ...] = ()
    tools_allowed: tuple[str, ...] = ()
    system: str = ""
    notes: list[str] = field(default_factory=list)


# Что ассистенту сказать про его задачу. Коротко намеренно: замер дня 29
# показал, что требование формата съедает у небольшой модели то внимание,
# которым она читает выдержки.
HELP_SYSTEM = (
    "Тебя спрашивают о проекте, из которого ты собран. Отвечай по выдержкам из "
    "его документации и кода и называй файлы, на которые опираешься. Чего в "
    "выдержках нет — того не придумывай: скажи, что не нашлось, и предложи, "
    "где посмотреть. Про текущее состояние репозитория — ветку, изменённые "
    "файлы, diff — спрашивай инструментами, а не по памяти: память о коде "
    "устаревает в тот момент, когда его правят."
)

# Что сказать модели, когда инструменты команде нужны, а в запрос не попали.
#
# Прямо названы два соблазна, в которые она иначе впадает. Первый — ответить по
# выдержкам: среди них может лежать исходный код самих инструментов, и на
# вопрос «какая сейчас ветка» приходит пересказ project_mcp.py с цитатой из
# докстринга — уверенный ответ ни о чём. Второй — ответить по памяти, то есть
# назвать ветку, которую модель видела в обучении или в прошлой реплике.
NO_TOOLS = (
    "Инструменты, которые нужны этой команде, в запрос НЕ попали: {tools}. "
    "Их сервер выключен во вкладке «MCP» или не отвечает.\n"
    "Поэтому о текущем состоянии репозитория — ветке, изменённых файлах, diff, "
    "последних коммитах — сказать нечего, и это надо сказать прямо: «нечем "
    "посмотреть, включите сервер проекта во вкладке MCP». Не отвечай по "
    "памяти. И не отвечай по выдержкам: в них может оказаться исходный код "
    "этих самых инструментов, но код, который умеет узнать ветку, — это не "
    "ветка."
)

# Пул для вопросов о проекте — десять, а не тридцать из умолчания.
#
# Замер дня 31 на двенадцати вопросах с известными файлами-ответами: при пуле
# 30 эталонный файл доходил до верхней тройки в 1 случае из 6 по вопросам о
# реализации, при пуле 10 — в 3 из 6, а по документации стало 6 из 6 против
# 5 из 6. Против интуиции, но объяснимо: чем шире пул, тем больше в слияние
# попадает кусков прозы, которые выигрывают словесный поиск у кода, потому
# что вопрос задан по-русски, а имена в коде английские.
HELP_POOL = 10

HELP_TEXT = """Спрашивайте о проекте так: `/help <вопрос>`.

Что ассистент видит:
- **документацию и код проекта** — поиском по двум наборам выдержек;
- **состояние репозитория** — ветку, изменённые файлы, diff, последние
  коммиты; это он берёт инструментами, то есть всегда свежим.

Примеры вопросов:
- `/help какая сейчас ветка и что в ней изменено`
- `/help где лежит проверка цитат`
- `/help зачем выкатка сверяет состав каталога на сервере`

Чего ассистент не видит: содержимое файлов вне индекса и правки, сделанные
после его сборки. Индекс — снимок; пересобрать его командой
`python manage.py index-project <логин>`."""


def parse(text: str) -> Условия | None:
    """Разбирает строку сообщения. Не команда — None, и ход идёт обычным путём."""
    строка = (text or "").strip()
    if not строка.startswith(PREFIX):
        return None
    слово, _, остаток = строка[len(PREFIX):].partition(" ")
    разбор = РЕЕСТР.get(слово.lower())
    return разбор(остаток.strip()) if разбор else None


def _help(вопрос: str) -> Условия:
    if not вопрос:
        return Условия(name="help", answer=HELP_TEXT)
    return Условия(
        name="help",
        question=вопрос,
        rag_mode=db.RAG_ALWAYS,
        rag_pool=HELP_POOL,
        attach_titles=(codebase.DOCS_TITLE, codebase.CODE_TITLE),
        # Разрешаем только инструменты про репозиторий. Это не «включить всё»:
        # правило дня 29 снимает на местной модели в режиме «всегда искать»
        # вообще все схемы, потому что небольшая модель уходит в инструмент
        # вместо ответа. Список разрешённых — щель в этом правиле ровно на
        # ширину git, и минимум задания («хотя бы текущая ветка») через неё
        # проходит, а найденная тогда беда не возвращается.
        tools_allowed=("git_branch", "changed_files", "git_diff", "recent_commits"),
        system=HELP_SYSTEM,
    )


РЕЕСТР = {"help": _help}


def attach_collections(conversation_id: int, user_id: int,
                       titles: tuple[str, ...]) -> list[str]:
    """Подключает наборы по названию. Отдаёт то, чего не нашлось.

    Не нашлось — не беда команды: наборы собираются отдельной командой, и
    сказать об этом человеку честнее, чем молча искать в пустоте.
    """
    import rag

    есть = {c["title"]: c for c in rag.list_collections(user_id)}
    пропали = []
    for название in titles:
        набор = есть.get(название)
        if набор is None:
            пропали.append(название)
            continue
        rag.attach(conversation_id, набор["id"], True)
    return пропали
