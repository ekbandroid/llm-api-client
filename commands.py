#
# Прямо названы два соблазна, в которые она иначе впадает. Первый — ответить по
# выдержкам: среди них может лежать исходный код самих инструментов, и на
# вопрос «какая сейчас ветка» приходит пересказ project_mcp.py с цитатой из
# докстринга — уверенный ответ ни о чём. Второй — ответить по памяти, то есть
# назвать ветку, которую модель видела в обучении или в прошлой реплике.
# Общая часть: что нельзя делать, оставшись без инструментов. Она одинакова в
