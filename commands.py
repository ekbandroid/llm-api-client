"""Команды чата: строка, начинающаяся со слеша, меняет условия одного хода.

Зачем реестр, а не один `if` в обработчике. Команда — это не текст вопроса, а
набор условий, при которых на вопрос отвечают: какие наборы документов
подключены, в каком режиме идёт поиск, какие инструменты лежат в запросе.
Таких наборов условий будет больше одного (день 32 добавит ревью кода), и
место, где они перечислены, должно быть одно.

Условия задаются **на один ход**. Диалог от команды не превращается
необратимо в «ассистента разработчика»: следующий вопрос без слеша пойдёт
обычным путём, и это видно по тому, что в запросе нет блока про проект.
Исключение — подключение наборов: оно постоянное и намеренно видимое, во
вкладке «Документы» появится отметка. Прятать от человека, что к его диалогу
прицепили двести килобайт README, нельзя.
"""

import re
from dataclasses import dataclass, field

import codebase
import db

# Приставка, по которой строка считается командой. Пробел после неё не нужен:
# «/help» без вопроса — тоже команда, и у неё свой ответ.
PREFIX = "/"


@dataclass
class Условия:
    """Чем ход по команде отличается от обычного.

    question — текст, который увидит модель вместо исходной строки с командой.
    Пустой означает, что обращаться к модели не нужно вовсе: ответ готов.
    """

    name: str
    question: str = ""
    answer: str = ""
    rag_mode: str = ""
    rag_pool: int = 0
    attach_titles: tuple[str, ...] = ()
    tools_allowed: tuple[str, ...] = ()
    system: str = ""
    # Номер тикета, который приложение подставит в запрос само. Ноль — без
    # тикета: /support можно спросить и просто так, как обычный FAQ.
    ticket: int = 0
    # Сколько кругов «модель просит инструмент — приложение выполняет»
    # разрешено этому ходу. Ноль — общий предел приложения. Своё число нужно
    # там, где работа сама по себе длинная: см. _project.
    rounds: int = 0
    # Номера issue для /issue и признак последовательного прогона. Пустой
    # кортеж — команда не про них.
    issues: tuple[int, ...] = ()
    one_by_one: bool = False
    notes: list[str] = field(default_factory=list)


