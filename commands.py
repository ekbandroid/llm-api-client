def _support(остаток: str) -> Условия:
    """`/support [номер] вопрос`. Номер необязателен."""
    номер, вопрос = 0, остаток
    первое, _, хвост = остаток.partition(" ")
    if первое.isdigit():
        номер, вопрос = int(первое), хвост.strip()

    if not вопрос:
        return Условия(name="support", answer=SUPPORT_TEXT)
    return Условия(
        name="support",
        question=вопрос,
        ticket=номер,
        rag_mode=db.RAG_ALWAYS,
        rag_pool=SUPPORT_POOL,
        attach_titles=(codebase.SUPPORT_TITLE, codebase.DOCS_TITLE),
        # Инструменты — для доборов: другие обращения того же человека,
        # похожие беды. Сам тикет подставляет приложение, а не выпрашивает
        # модель: день 29 показал, что на вызов инструмента надеяться нельзя.
        tools_allowed=("ticket", "user_tickets", "find_tickets"),
        system=SUPPORT_SYSTEM,
    )


