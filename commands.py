# сидит, и ветку ему завело приложение.
SUBAGENT_TOOLS = ("list_project_files", "read_file", "find_in_files",
                  "replace_in_file", "write_file", "run_checks")


def субагент(задача: str) -> Условия:
    """Условия хода субагента: пять инструментов, свой промпт, свой предел."""
    return Условия(
        name="subagent",
        question=задача,
        tools_allowed=SUBAGENT_TOOLS,
        # Столько же, сколько у /project, и по той же причине: обзор плюс
        # правка плюс круги на починку по выводу ворот.
        rounds=12,
        system=SUBAGENT_SYSTEM,
    )


ISSUE_TEXT = """Сделать задачи по номерам issue: `/issue 12,13,14`.

Что происходит: приложение читает названные issue из GitHub, заводит на
каждую рабочее дерево и ветку `task-<номер>`, и три субагента пишут код
одновременно — каждый у себя. Готовое проверяют ворота: сборка, тесты,
разбор javascript и shell. Прошедшее уходит в репозиторий отдельной веткой,
и на неё даётся ссылка на создание PR.

Ворота — это код, а не модель: «собралось» и «тест прошёл» решает код
возврата. Спрашивать об этом модель значило бы разрешить ей ответить «да».

`/issue 12,13,14 по-одному` — то же, но последовательно. Нужно для сравнения:
сколько даёт параллельность на этой задаче.

Границы: пушится только новая ветка `task-*`. В master пайплайн не пишет
никогда и force не делает. Отменить — `git push origin --delete task-<номер>`.
PR и слияние остаются за вами."""


def _issue(остаток: str) -> Условия:
    """`/issue <номера>` — пайплайн дня 35, а не один ход с моделью."""
    по_одному = "по-одному" in остаток or "по одному" in остаток
    номера = tuple(int(н) for н in re.findall(r"\d+", остаток))
    if not номера:
        return Условия(name="issue", answer=ISSUE_TEXT)
    return Условия(name="issue", issues=номера, one_by_one=по_одному)


РЕЕСТР = {"help": _help, "support": _support, "project": _project,
           "issue": _issue}


def attach_collections(conversation_id: int, user_id: int,
                       titles: tuple[str, ...]) -> list[str]:
    """Подключает наборы по названию. Отдаёт то, чего не нашлось.

    Не нашлось — не беда команды: наборы собираются отдельной командой, и
    сказать об этом человеку честнее, чем молча искать в пустоте.
    """
    import rag

    есть = {c["title"]: c for c in rag.list_collections(user_id)}
    пропали = []
    for название in titles:
        набор = есть.get(название)
        if набор is None:
            пропали.append(название)
            continue
        rag.attach(conversation_id, набор["id"], True)
    return пропали
