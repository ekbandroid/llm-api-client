"""Проверка ответа на опору в документах: цитаты и названные источники.

Просить модель «указывай источник и цитируй» — это просьба, а её вес в
запросе такой же, как у всего остального текста. Проверить просьбу дешевле,
чем усилить: цитата либо есть в найденных выдержках дословно, либо нет, и это
решается поиском подстроки, а не доверием.

Модуль ничего не запрещает и ничего не переписывает. Он считает: сколько в
ответе цитат, сколько из них нашлось в выдержках, названы ли файлы. Дальше
число видит человек — рядом с ответом, в той же строке, где состав памяти.
Ошибиться в сторону тревоги тут хуже, чем пропустить: ложная тревога учит не
доверять проверке, поэтому всё спорное считается нормой.

    python grounding.py            # проверка на примерах
"""

import re
import unicodedata

# Кавычки, которыми размечают цитату. Прямые кавычки сюда не входят намеренно:
# в них чаще оказываются названия и слова «в кавычках», а не цитаты, и
# проверять их значило бы ругаться на ровном месте.
PAIRS = (("«", "»"), ("“", "”"), ("„", "“"))

# Короче этого цитату не проверяем. «Геркулес» или «Антилопа» — название, а не
# Все кавычки, какие встречаются в тексте, — для сравнения они равны.
QUOTE_MARKS = "«»\u201c\u201d\u201e\u201f\u2018\u2019'\""

# утверждение: искать его дословно бессмысленно, оно и так найдётся.
# Короче этого ёлочки считаем не цитатой, а названием или оборотом.
#
# В русском тексте ёлочки размечают и то и другое, и отличать приходится по
# длине. Замер на живых ответах по книге: настоящие цитаты выходили на 52, 60,
# 78, 111, 115, 194 и 257 символов, а в промахи попадали «Золотой телёнок.txt»
# (19), «делом Корейко» (13) и «детей лейтенанта Шмидта» (23) — имя файла и
# два оборота, которые модель просклоняла под свою фразу. Склонение не выдумка,
# а грамматика, и ругаться на него значит учить не доверять проверке.
MIN_QUOTE = 40

# А часть цитаты с пропуском может быть и короткой: «начало… конец» стоит
# проверить целиком, раз уж в кавычки взят длинный кусок.
MIN_PART = 12

# Чем разделена цитата с пропуском: «начало… конец». Каждая часть проверяется
# отдельно, иначе пропуск в середине всегда давал бы промах.
GAP = re.compile(r"\s*(?:\.{3}|…|\[\.{3}\]|\[…\])\s*")


def normalize(text: str) -> str:
    """Приводит текст к виду, в котором сравнение не придирается к мелочам.

    Схлопывает пробелы (в книге после точки их два, в ответе модели один),
    равняет ё с е и тире с дефисом, снимает регистр. Всё это различия
    набора, а не содержания: цитата с ними остаётся той же цитатой.
    """
    text = unicodedata.normalize("NFKC", text or "").lower().replace("ё", "е")
    text = re.sub(r"[‐-―−-]", "-", text)
    # Кавычки внутри цитаты равняем все к одной. Проверено на живом ответе:
    # в документе «представительские расходы» стоят в ёлочках, модель привела
    # их в прямых — и длинная верная цитата не сошлась из-за одних кавычек.
    text = re.sub(r"[" + "".join(QUOTE_MARKS) + "]", '"', text)
    text = re.sub(r"[ \s]+", " ", text)
    return text.strip()


def quotes(answer: str) -> list[str]:
    """Вытаскивает из ответа то, что помечено кавычками как цитата."""
    found: list[str] = []
    for left, right in PAIRS:
        # Нежадно и без вложенности: кавычки внутри цитаты — редкость, а
        # жадный поиск склеил бы две цитаты в одну через весь абзац.
        for кусок in re.findall(f"{left}([^{left}{right}]+){right}", answer or ""):
            кусок = кусок.strip()
            if len(кусок) >= MIN_QUOTE:
                found.append(кусок)
    return found


# Заголовок выдержки в ответе инструмента: «[2] набор · файл · раздел · id 17
# (близость 0.45)». Разбираем его, чтобы знать, из какого файла каждый кусок,
# и чтобы проверять цитаты по тексту, а не по всему ответу инструмента вместе
# с его же пояснениями.
# Начало хвоста с правилами — первая строка ANSWER_RULES из research_mcp.
TAIL = re.compile(r"^Это выдержки из документов", re.M)

HEADER = re.compile(
    r"^\[(\d+)\]\s*(?P<collection>[^·\n]*)·\s*(?P<source>[^·\n]*)·"
    r"\s*(?P<section>[^·\n]*)·\s*id\s*(?P<chunk_id>\S+)[^\n]*$",
    re.M)


def from_tool_output(text: str) -> list[dict]:
    """Разбирает ответ search_docs обратно в выдержки.

    Приложение получает от инструмента готовый текст, а проверять цитаты надо
    по самим выдержкам: в хвосте того же текста лежат правила ответа, и
    цитата, совпавшая с ними, считалась бы подтверждённой зря.
    """
    # Хвост с правилами ответа отрезаем: он идёт сразу за последней выдержкой,
    # и без этого цитата, совпавшая со словами правил, засчиталась бы как
    # найденная в документе. Проверено — именно так и происходило.
    text = TAIL.split(text or "", 1)[0]
    куски: list[dict] = []
    места = list(HEADER.finditer(text))
    for n, m in enumerate(места):
        конец = места[n + 1].start() if n + 1 < len(места) else len(text)
        куски.append({
            "collection": m.group("collection").strip(),
            "source": m.group("source").strip(),
            "section": m.group("section").strip(),
            "chunk_id": m.group("chunk_id").strip(),
            "text": text[m.end():конец].strip(),
        })
    return куски


def check(answer: str, excerpts: list[dict]) -> dict:
    """Насколько ответ опирается на выдержки: цитаты и названные источники.

    excerpts — то, что нашёл поиск: словари с `text` и `source`. Возвращается
    словарь для телеметрии и для строки под ответом.
    """
    if not excerpts:
        return {}
    основа = normalize("\n".join(e.get("text", "") for e in excerpts))
    источники = {e.get("source", "") for e in excerpts if e.get("source")}
    # Набор модель называет чаще файла: в заголовке выдержки стоят оба, и
    # «Золотой телёнок.txt» — имя набора, а «Золотои_теленок.txt» — файла.
    наборы = {e.get("collection", "") for e in excerpts if e.get("collection")}

    # Имя файла модель тоже берёт в ёлочки — это ссылка на источник, а не
    # цитата из него, и искать его в тексте документа бессмысленно. Проверено:
    # «Рога и копыта — отчёт.txt» попадало в промахи при совершенно верном ответе.
    имена = {normalize(s) for s in источники | наборы}
    имена |= {normalize(s.rsplit('.', 1)[0]) for s in источники | наборы}

    проверено, не_нашлись = 0, []
    for цитата in quotes(answer):
        if normalize(цитата) in имена:
            continue
        # Цитата с пропуском: каждая часть ищется сама по себе.
        части = [normalize(ч) for ч in GAP.split(цитата)]
        части = [ч for ч in части if len(ч) >= MIN_PART]
        if not части:
            continue
        проверено += 1
        if not all(ч in основа for ч in части):
            не_нашлись.append(цитата)

    текст = normalize(answer)
    # Источник назван, если в ответе есть имя файла или имя набора: человеку
    # важно, что ответ сослался на документ, а не какое из двух имён он выбрал.
    названы = sorted(s for s in источники
                     if any(normalize(n) in текст
                            or normalize(n.rsplit('.', 1)[0]) in текст
                            for n in {s, *наборы}))
    return {
        "quotes": проверено,
        "verified": проверено - len(не_нашлись),
        "missing": не_нашлись[:3],
        "sources": len(источники),
        "named": len(названы),
    }


def describe(report: dict) -> str:
    """Короткая строка для человека. Пусто — если показывать нечего."""
    if not report:
        return ""
    части = []
    if report["quotes"]:
        промах = report["quotes"] - report["verified"]
        части.append(f"цитат {report['quotes']}" + (
            ", все найдены в документах" if not промах
            else f", не нашлось в документах: {промах}"))
    else:
        части.append("цитат в ответе нет")
    части.append(f"источников названо {report['named']} из {report['sources']}")
    return "Опора на документы: " + ", ".join(части) + "."


def main() -> None:
    выдержки = [{"source": "отчёт.txt",
                 "text": "Курьером служит Паниковский.  Оклад курьера — "
                         "тридцать один рубль пятьдесят копеек; сверх того ему "
                         "полагается гусь раз в две недели."}]
    ответ_инструмента = (
        "Найдено в документах (2) · судья оставил 2 из 9:\n"
        "\n[1] Отчёт · отчёт.txt · символы 0–600 · id col4:отчёт.txt#0 (близость 0.43)\n"
        "Курьером служит Паниковский.  Оклад курьера — тридцать один рубль.\n"
        "\n[2] Отчёт · отчёт.txt · символы 500–1100 · id col4:отчёт.txt#1 (близость 0.28)\n"
        "Контора занимает половину дома номер восемь.\n"
        "\nЭто выдержки из документов пользователя. Отвечай только по ним."
    )
    разобрано = from_tool_output(ответ_инструмента)
    print("разбор ответа инструмента:", len(разобрано), "выдержки")
    for к in разобрано:
        print(f"   {к['source']} · {к['section']} · {к['chunk_id']} · {len(к['text'])} символов")
    print("правила в текст выдержек не попали:",
          all("Отвечай только по ним" not in к["text"] for к in разобрано))
    print()

    примеры = [
        ("По файлу отчёт.txt: «Курьером служит Паниковский. Оклад курьера — тридцать один рубль пятьдесят копеек»", "цитата дословная"),
        ("В отчёт.txt сказано: «Курьером служит Паниковский… полагается гусь раз в две недели»", "цитата с пропуском"),
        ("Из отчёт.txt: «Курьером служит Паниковский. Оклад курьера — сорок рублей ровно, без всяких гусей»", "цитата выдумана"),
        ("Речь о «Рога и копыта — отчёт.txt», там всё сказано.",
         "имя файла в ёлочках — не цитата"),
        ("Оклад курьера — 31 рубль 50 копеек.", "без цитат и без источника"),
        ("По файлу отчёт.txt оклад курьера 31 рубль.", "источник есть, цитат нет"),
    ]
    for ответ, имя in примеры:
        отчёт = check(ответ, выдержки)
        print(f"{имя:28} -> {отчёт}")
        print(f"{'':28}    {describe(отчёт)}")


if __name__ == "__main__":
    main()
